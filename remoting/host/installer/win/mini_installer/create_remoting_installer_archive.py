"""Packs Chrome Remote Desktop host payload files and setup binary into a .7z
archive and generates a Windows resource script (.rc) embedding the archive in
remoting_mini_installer.exe.
"""

import argparse
import os
import shutil
import subprocess
import sys

# Must match `kArchiveResourceName` and `kArchiveResourceType` in
# `remoting/host/installer/win/mini_installer/mini_installer_constants.h`.
_ARCHIVE_RESOURCE_NAME = 'REMOTING.7Z'
_ARCHIVE_RESOURCE_TYPE = 'B7'


def _stage_files(staging_dir: str, input_files: list[str]) -> list[str]:
  if os.path.exists(staging_dir):
    shutil.rmtree(staging_dir)
  os.makedirs(staging_dir, exist_ok=True)

  staged_names = set()
  for src_path in input_files:
    filename = os.path.basename(src_path)
    if filename in staged_names:
      raise ValueError(f'Duplicate input filename: {filename}')
    dst_path = os.path.join(staging_dir, filename)
    shutil.copyfile(src_path, dst_path)
    staged_names.add(filename)
  return sorted(staged_names)


def _create_7z_archive(
  lzma_exec: str,
  staging_dir: str,
  staged_filenames: list[str],
  output_archive: str,
  fast_compression: bool,
) -> None:
  abs_lzma_exec = os.path.abspath(lzma_exec)
  abs_output_archive = os.path.abspath(output_archive)
  os.makedirs(os.path.dirname(abs_output_archive), exist_ok=True)
  if os.path.exists(abs_output_archive):
    os.remove(abs_output_archive)

  cmd = [abs_lzma_exec, 'a', '-t7z']
  if fast_compression:
    # Use the same 4-coder BCJ2 + LZMA pipeline as official builds with fast
    # (-mx1) dictionary settings so developer builds exercise the identical
    # decompression path in //third_party/lzma_sdk (which compiles out the
    # 1-stream BCJ filter via Z7_NO_METHODS_FILTERS).
    cmd.extend(
      [
        '-m0=BCJ2',
        '-m1=LZMA',
        '-m2=LZMA',
        '-m3=LZMA',
        '-mb0:1',
        '-mb0s1:2',
        '-mb0s2:3',
        '-mx1',
      ]
    )
  else:
    cmd.extend(
      [
        '-m0=BCJ2',
        '-m1=LZMA:d27:fb128',
        '-m2=LZMA:d22:fb128:mf=bt2',
        '-m3=LZMA:d22:fb128:mf=bt2',
        '-mb0:1',
        '-mb0s1:2',
        '-mb0s2:3',
      ]
    )
  # Strip file modification timestamps and file attributes for deterministic
  # archive output across Linux and Windows build hosts.
  cmd.extend(['-mtm-', '-mtr-'])
  cmd.append(abs_output_archive)
  cmd.extend(staged_filenames)

  try:
    subprocess.run(
      cmd,
      cwd=os.path.abspath(staging_dir),
      check=True,
      stdout=subprocess.PIPE,
      stderr=subprocess.STDOUT,
      text=True,
    )
  except subprocess.CalledProcessError as e:
    if e.stdout:
      sys.stderr.write(e.stdout)
    raise


def _write_resource_file(resource_file_path: str, archive_path: str) -> None:
  os.makedirs(
    os.path.dirname(os.path.abspath(resource_file_path)), exist_ok=True
  )
  # `archive_path` is passed relative to `root_build_dir` (matching
  # //chrome/installer/mini_installer and //chrome/updater/win/installer) so
  # `rc.py /showIncludes` emits a `root_build_dir`-relative dependency path for
  # Ninja.
  normalized_archive_path = archive_path.replace('\\', '/')
  with open(resource_file_path, 'w', encoding='utf-8') as f:
    f.write('// Auto-generated by create_remoting_installer_archive.py.\n')
    f.write(
      f'{_ARCHIVE_RESOURCE_NAME} {_ARCHIVE_RESOURCE_TYPE}\n'
      f'    "{normalized_archive_path}"\n'
    )


def main() -> int:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument(
    '--lzma-exec', required=True, help='Path to the 7za executable.'
  )
  parser.add_argument(
    '--staging-dir',
    required=True,
    help='Temporary staging directory for archive inputs.',
  )
  parser.add_argument(
    '--output-archive',
    required=True,
    help='Output path for the generated .7z archive.',
  )
  parser.add_argument(
    '--resource-file-path',
    required=True,
    help='Output path for the generated .rc file.',
  )
  parser.add_argument(
    '--fast-archive-compression',
    action='store_true',
    help='Use fast compression (-mx1) for developer builds.',
  )
  parser.add_argument(
    '--input-files',
    nargs='+',
    required=True,
    help='Files to stage at the root of the archive.',
  )
  args = parser.parse_args()

  staged_filenames = _stage_files(args.staging_dir, args.input_files)
  _create_7z_archive(
    args.lzma_exec,
    args.staging_dir,
    staged_filenames,
    args.output_archive,
    args.fast_archive_compression,
  )
  _write_resource_file(args.resource_file_path, args.output_archive)
  return 0


if __name__ == '__main__':
  sys.exit(main())
