"""Unit tests for create_remoting_installer_archive.py."""

import io
import os
import subprocess
import tempfile
import unittest
from unittest import mock

import create_remoting_installer_archive


class CreateRemotingInstallerArchiveTest(unittest.TestCase):
  def test_stage_files_copies_and_cleans_existing_staging_dir(self):
    with tempfile.TemporaryDirectory() as temp_dir:
      src_dir = os.path.join(temp_dir, 'src')
      staging_dir = os.path.join(temp_dir, 'staging')
      os.makedirs(src_dir)
      os.makedirs(staging_dir)

      stale_file = os.path.join(staging_dir, 'stale.txt')
      with open(stale_file, 'w', encoding='utf-8') as f:
        f.write('stale')

      file_b = os.path.join(src_dir, 'b.exe')
      file_a = os.path.join(src_dir, 'a.dll')
      with open(file_b, 'w', encoding='utf-8') as f:
        f.write('binary_b')
      with open(file_a, 'w', encoding='utf-8') as f:
        f.write('binary_a')

      staged = create_remoting_installer_archive._stage_files(
        staging_dir, [file_b, file_a]
      )
      self.assertEqual(staged, ['a.dll', 'b.exe'])
      self.assertEqual(sorted(os.listdir(staging_dir)), ['a.dll', 'b.exe'])

  def test_stage_files_rejects_duplicate_basenames(self):
    with tempfile.TemporaryDirectory() as temp_dir:
      dir1 = os.path.join(temp_dir, 'dir1')
      dir2 = os.path.join(temp_dir, 'dir2')
      staging_dir = os.path.join(temp_dir, 'staging')
      os.makedirs(dir1)
      os.makedirs(dir2)

      dup1 = os.path.join(dir1, 'payload.dll')
      dup2 = os.path.join(dir2, 'payload.dll')
      with open(dup1, 'w', encoding='utf-8') as f:
        f.write('1')
      with open(dup2, 'w', encoding='utf-8') as f:
        f.write('2')

      with self.assertRaisesRegex(
        ValueError, r'Duplicate input filename: payload\.dll'
      ):
        create_remoting_installer_archive._stage_files(
          staging_dir, [dup1, dup2]
        )

  def test_write_resource_file_normalizes_backslashes(self):
    with tempfile.TemporaryDirectory() as temp_dir:
      rc_path = os.path.join(temp_dir, 'gen', 'packed_files.rc')
      create_remoting_installer_archive._write_resource_file(
        rc_path, r'gen\remoting\mini_installer\remoting.7z'
      )
      with open(rc_path, 'r', encoding='utf-8') as f:
        content = f.read()
      self.assertEqual(
        content,
        '// Auto-generated by create_remoting_installer_archive.py.\n'
        'REMOTING.7Z B7\n'
        '    "gen/remoting/mini_installer/remoting.7z"\n',
      )

  @mock.patch('subprocess.run')
  def test_create_7z_archive_fast_and_official_flags(self, mock_run):
    with tempfile.TemporaryDirectory() as temp_dir:
      staging_dir = os.path.join(temp_dir, 'staging')
      os.makedirs(staging_dir)
      archive_path = os.path.join(temp_dir, 'out', 'remoting.7z')

      create_remoting_installer_archive._create_7z_archive(
        lzma_exec='7za',
        staging_dir=staging_dir,
        staged_filenames=['a.dll', 'b.exe'],
        output_archive=archive_path,
        fast_compression=True,
      )
      fast_cmd = mock_run.call_args[0][0]
      self.assertIn('-m0=BCJ2', fast_cmd)
      self.assertIn('-mx1', fast_cmd)
      self.assertIn('-mtm-', fast_cmd)
      self.assertIn('-mtr-', fast_cmd)

      mock_run.reset_mock()
      create_remoting_installer_archive._create_7z_archive(
        lzma_exec='7za',
        staging_dir=staging_dir,
        staged_filenames=['a.dll', 'b.exe'],
        output_archive=archive_path,
        fast_compression=False,
      )
      official_cmd = mock_run.call_args[0][0]
      self.assertIn('-m0=BCJ2', official_cmd)
      self.assertIn('-m1=LZMA:d27:fb128', official_cmd)
      self.assertNotIn('-mx1', official_cmd)
      self.assertIn('-mtm-', official_cmd)
      self.assertIn('-mtr-', official_cmd)

  @mock.patch('subprocess.run')
  def test_create_7z_archive_forwards_stdout_on_error(self, mock_run):
    mock_run.side_effect = subprocess.CalledProcessError(
      returncode=2, cmd=['7za'], output='7za failure details\n'
    )
    stderr_capture = io.StringIO()
    with (
      tempfile.TemporaryDirectory() as temp_dir,
      mock.patch('sys.stderr', stderr_capture),
    ):
      with self.assertRaises(subprocess.CalledProcessError):
        create_remoting_installer_archive._create_7z_archive(
          lzma_exec='7za',
          staging_dir=temp_dir,
          staged_filenames=['a.dll'],
          output_archive=os.path.join(temp_dir, 'remoting.7z'),
          fast_compression=True,
        )
    self.assertEqual(stderr_capture.getvalue(), '7za failure details\n')


if __name__ == '__main__':
  unittest.main()
