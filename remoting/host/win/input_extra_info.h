#ifndef REMOTING_HOST_WIN_INPUT_EXTRA_INFO_H_
#define REMOTING_HOST_WIN_INPUT_EXTRA_INFO_H_

#include <windows.h>

#include <cstdint>

namespace remoting {

// A unique signature stamped into INPUT.mi.dwExtraInfo and INPUT.ki.dwExtraInfo
// when injecting input via SendInput() on Windows.
// This allows local input monitors (such as MouseRawInputHandler and
// KeyboardRawInputHandler) to distinguish CRD's own injected input from
// legitimate local software-injected input generated by assistive technologies
// (e.g. On-Screen Keyboard, Voice Access, Eye Control) or touch emulation.
// While INPUT.mi.dwExtraInfo and INPUT.ki.dwExtraInfo accept a ULONG_PTR,
// Windows truncates this value in the RAWINPUT stream where
// RAWMOUSE.ulExtraInformation and RAWKEYBOARD.ExtraInformation are defined as
// 32-bit ULONG. Defining this signature as uint32_t reflects this constraint.
inline constexpr uint32_t kCrdInputExtraInfo = 0x43524430;  // 'CRD0'

// Returns true if the RAWINPUT event represents input injected by CRD.
// Remote (injected) input events do not specify a device handle and are
// stamped with kCrdInputExtraInfo. Software-injected input from assistive
// technologies or other local sources does not bear this signature and will
// return false so it can be handled as local input.
inline bool IsCrdInjectedInput(const RAWINPUT& event) {
  if (event.header.hDevice != nullptr) {
    return false;
  }
  if (event.header.dwType == RIM_TYPEMOUSE) {
    return event.data.mouse.ulExtraInformation == kCrdInputExtraInfo;
  }
  if (event.header.dwType == RIM_TYPEKEYBOARD) {
    return event.data.keyboard.ExtraInformation == kCrdInputExtraInfo;
  }
  return false;
}

}  // namespace remoting

#endif  // REMOTING_HOST_WIN_INPUT_EXTRA_INFO_H_
