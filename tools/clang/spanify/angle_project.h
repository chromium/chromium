#ifndef TOOLS_CLANG_SPANIFY_ANGLE_PROJECT_H_
#define TOOLS_CLANG_SPANIFY_ANGLE_PROJECT_H_

#include <string>
#include <vector>

#include "RawPtrHelpers.h"
#include "Util.h"
#include "clang/AST/ASTContext.h"
#include "clang/AST/Decl.h"
#include "clang/ASTMatchers/ASTMatchFinder.h"
#include "llvm/ADT/StringRef.h"
#include "project.h"

class AngleProject : public Project {
 public:
  constexpr AngleProject() = default;
  std::string_view GetSpanIncludePath() const override {
    return "common/span.h";
  }
  std::string_view GetSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result)
      const override {
    return "angle::Span";
  }
  std::string_view GetRawSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result)
      const override {
    return "RAW_SPAN_NOT_AVAILABLE";
  }
  std::string_view GetSpanFromRefRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result)
      const override {
    return "angle::span_from_ref";
  }
  std::string_view GetAsByteSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result)
      const override {
    return "angle::as_byte_span";
  }
  std::string_view GetAsWritableByteSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result)
      const override {
    return "angle::as_writable_byte_span";
  }
  std::string_view GetSafeConversionsIncludePath() const override {
    return "common/base/anglebase/numerics/safe_conversions.h";
  }
  std::string_view GetRawSpanIncludePath() const override {
    return "PATH_TO_RAW_SPAN_H_NOT_AVAILABLE";
  }
  std::string_view GetAutoSpanificationHelperIncludePath() const override {
    return "NOT_AVAILABLE base/containers/auto_spanification_helper.h";
  }
  std::string_view GetUnsafeTodoMacroName() const override {
    return "ANGLE_UNSAFE_TODO";
  }
  std::string_view GetUnsafeTodoIncludePath() const override {
    return "common/unsafe_buffers.h";
  }
  const std::vector<FuncMapping>& GetFuncMappingTable() const override {
    static const std::vector<FuncMapping> kFuncMappingTable = {};
    return kFuncMappingTable;
  }
  bool UseExplicitSizeForImplicitArrays() const override { return true; }
  bool IsExcludedFromProject(const clang::Decl& Node) const override {
    const clang::SourceManager& source_manager =
        Node.getASTContext().getSourceManager();

    std::string filename = raw_ptr_plugin::GetFilename(
        source_manager, raw_ptr_plugin::getRepresentativeLocation(Node),
        raw_ptr_plugin::FilenameLocationType::kSpellingLoc);

    llvm::StringRef file(filename);

    // A file is off limits when it is not hand-maintained ANGLE C++: either a
    // code generator owns it (/shaders/gen/, context_private_call.inl.h) or it
    // is a flex/bison grammar rather than a translation unit (.l, .y). The
    // remaining cases -- autogen paths, code outside the submodule, and
    // third-party libraries vendored inside it -- are shared by all four 2P
    // projects.
    auto is_excluded = [](llvm::StringRef f) -> bool {
      return f.contains("/shaders/gen/") ||
             f.contains("context_private_call.inl.h") || f.ends_with(".l") ||
             f.ends_with(".y") ||
             IsExcludedFromSubmodule(f, "third_party/angle/",
                                     "tools/clang/spanify/tests/angle/");
    };

    if (is_excluded(file)) {
      return true;
    }

    // If a function is declared in an excluded header (e.g. the autogenerated
    // Context_gles_ext_autogen.h, or a vendored third-party header) but
    // defined out-of-line in a regular source file (e.g.
    // src/libANGLE/Context.cpp), checking only the definition's file would
    // fail to exclude it. Spanifier would then rewrite the definition's
    // signature but leave the declaration intact, causing Clang out-of-line
    // signature mismatches. We need to check all redeclarations to keep them
    // synchronized.
    const clang::FunctionDecl* func =
        llvm::dyn_cast<clang::FunctionDecl>(&Node);
    if (!func) {
      if (const auto* parm = llvm::dyn_cast<clang::ParmVarDecl>(&Node)) {
        func =
            llvm::dyn_cast_or_null<clang::FunctionDecl>(parm->getDeclContext());
      }
    }
    if (func) {
      for (const clang::FunctionDecl* redecl : func->redecls()) {
        if (redecl != func) {
          std::string redecl_file = raw_ptr_plugin::GetFilename(
              source_manager,
              raw_ptr_plugin::getRepresentativeLocation(*redecl),
              raw_ptr_plugin::FilenameLocationType::kSpellingLoc);
          if (is_excluded(llvm::StringRef(redecl_file))) {
            return true;
          }
        }
      }
    }

    return false;
  }
};

#endif  // TOOLS_CLANG_SPANIFY_ANGLE_PROJECT_H_
