#ifndef TOOLS_CLANG_SPANIFY_PROJECT_H_
#define TOOLS_CLANG_SPANIFY_PROJECT_H_

#include <string>
#include <string_view>
#include <vector>

#include "RawPtrHelpers.h"
#include "clang/AST/Decl.h"
#include "clang/ASTMatchers/ASTMatchFinder.h"
#include "clang/Basic/SourceLocation.h"
#include "llvm/ADT/StringRef.h"

struct RangedReplacement {
  clang::SourceRange range;
  std::string text;
};

// Specifies a checked cast edit, such as `base::checked_cast<size_t>(...)` or
// `SkTo<size_t>(...)`.
struct CheckedCastReplacement {
  RangedReplacement opener;
  RangedReplacement closer;
};

struct FuncMapping {
  const std::string function_name;
  const std::string replacement_function_name;
};

class Project {
 public:
  constexpr Project() = default;
  virtual ~Project() = default;
  virtual std::string_view GetSpanIncludePath() const = 0;
  virtual std::string_view GetSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result) const = 0;
  virtual std::string_view GetRawSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result) const = 0;
  virtual std::string_view GetSpanFromRefRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result) const = 0;
  virtual std::string_view GetAsByteSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result) const = 0;
  virtual std::string_view GetAsWritableByteSpanRelativePath(
      const clang::ast_matchers::MatchFinder::MatchResult& result) const = 0;
  virtual std::string_view GetSafeConversionsIncludePath() const = 0;
  virtual CheckedCastReplacement GetCheckedCastReplacement(
      clang::SourceRange range) const {
    return CheckedCastReplacement{
        .opener = {.range = range.getBegin(),
                   .text = "base::checked_cast<size_t>("},
        .closer = {.range = range.getEnd(), .text = ")"}};
  }
  virtual std::string_view GetRawSpanIncludePath() const = 0;
  virtual std::string_view GetAutoSpanificationHelperIncludePath() const = 0;
  virtual std::string_view GetPreIncrementSpanName() const {
    return "base::PreIncrementSpan";
  }
  virtual std::string_view GetPostIncrementSpanName() const {
    return "base::PostIncrementSpan";
  }
  virtual std::string_view GetUnsafeTodoMacroName() const {
    return "UNSAFE_TODO";
  }
  virtual std::string_view GetUnsafeTodoIncludePath() const {
    return "base/compiler_specific.h";
  }
  virtual const std::vector<FuncMapping>& GetFuncMappingTable() const = 0;
  virtual bool IsExcludedFromProject(const clang::Decl& Node) const = 0;
  virtual bool SupportsStaticExtent() const { return true; }
  virtual bool UseExplicitSizeForImplicitArrays() const { return false; }

 protected:
  // Returns true if `file` must not be rewritten while spanifying a 2P
  // submodule (ANGLE, Dawn, Skia, WebRTC).
  //
  // `file` is the path as clang saw it. Clang prepends the compilation
  // directory to the compile database entries, so it is always rooted at the
  // Chromium checkout, e.g.
  //   .../src/third_party/angle/out/rewrite-win/../../src/common/foo.cpp
  // Every file belonging to the submodule therefore contains
  // `submodule_prefix`; files that do not are outside of it (Chromium core,
  // another submodule) and are excluded. Note this assumes
  // the submodule is checked out at third_party/<project>/ inside a Chromium
  // checkout, which is how tools/clang/spanify/rewrite_multiple_platforms.py
  // drives it.
  //
  // Third-party libraries vendored *inside* the submodule (e.g.
  // third_party/angle/src/common/third_party/xxhash/) are excluded as well.
  //
  // `test_prefix` is the spanify test corpus root for the project. Test files
  // live under tools/ rather than under the submodule, so the test root plays
  // the role of the submodule root for them.
  static bool IsExcludedFromSubmodule(llvm::StringRef file,
                                      llvm::StringRef submodule_prefix,
                                      llvm::StringRef test_prefix) {
    // Autogenerated files are owned by their generator, never rewrite them.
    if (file.contains_insensitive("autogen")) {
      return true;
    }
    if (file.contains(test_prefix)) {
      return file.split(test_prefix).second.contains("third_party/");
    }
    if (!file.contains(submodule_prefix)) {
      return true;
    }
    // Anchor on the *first* occurrence: `split()`, never `rsplit()`. Because
    // `submodule_prefix` itself begins with "third_party/", stripping a later
    // occurrence would swallow the vendored directory this check looks for.
    // Submodules do vendor each other -- ANGLE pulls Dawn, and Dawn's DEPS
    // pulls ANGLE back under the dawn_standalone condition -- so a path like
    //   third_party/angle/third_party/dawn/third_party/angle/foo.h
    // can reach this line, and only the first anchor leaves its middle
    // third_party/ visible.
    return file.split(submodule_prefix).second.contains("third_party/");
  }
};
#endif  // TOOLS_CLANG_SPANIFY_PROJECT_H_
