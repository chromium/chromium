std::optional<int> LookupStringInFixedSet(base::span<const uint8_t> graph,
                                          std::string_view key) {
  // Do an incremental lookup until either the end of the graph is reached, or
  // until every character in `key` is consumed.
  FixedSetIncrementalLookup lookup(graph);
  for (char input : key) {
    if (!lookup.Advance(input)) {
      return std::nullopt;
    }
  }
  // The entire input was consumed without reaching the end of the graph. Return
  // the result code (if present) for the current position, or std::nullopt.
  return lookup.GetResultForCurrentSequence();
}

// This function is only used by GetRegistryInTrimmedHost(), but is
// implemented here to allow inlining of
// LookupStringInFixedSet::GetResultForCurrentSequence() and
// LookupStringInFixedSet::Advance() at compile time. Tests on x86_64 linux
// indicated about 10% increased runtime cost for GetRegistry() in average
// if the implementation of this function was separated from the lookup methods.
std::optional<SuffixMatch> LookupSuffixInReversedSet(
    base::span<const uint8_t> graph,
    bool include_private,
    std::string_view host) {
  FixedSetIncrementalLookup lookup(graph);
  std::optional<SuffixMatch> result;
  // Look up host from right to left.
  for (std::string_view remaining = host;
       !remaining.empty() && lookup.Advance(remaining.back());
       remaining.remove_suffix(1)) {
    // Only host itself or a part that follows a dot can match.
    if (remaining.size() == 1 || remaining[remaining.size() - 2] == '.') {
      std::optional<DomainRuleTags> value =
          lookup.GetResultForCurrentSequence().transform(
              DomainRuleTags::FromEnumBitmask);
      if (value.has_value()) {
        // Break if private and private rules should be excluded.
        if (value->Has(DomainRuleTag::kPrivate) && !include_private) {
          break;
        }
        // Save matching suffix and return value. Since hosts are looked up
        // from right to left, the last saved values will be from the longest
        // match.
        result = SuffixMatch{
            .tags = *value,
            .suffix = host.substr(remaining.size() - 1),
        };
      }
    }
  }
  return result;
}

std::vector<std::string> EnumerateDafsaLanguageForTesting(
    base::span<const uint8_t> graph) {
  FixedSetIncrementalLookup query(graph);
  std::string sequence;
  std::vector<std::string> language;
  RecursivelyEnumerateDafsaLanguage(query, sequence, language);
  return language;
}

