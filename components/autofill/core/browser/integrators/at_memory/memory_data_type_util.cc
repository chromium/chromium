// Parses a date string in "YYYY-MM-DD" format (such as generated by
// `SerializeDate`, optionally followed by time separated by ' ' or 'T') into a
// `personal_context::proto::Date`. Returns `std::nullopt` if `str` is not in
// the expected format or cannot be parsed.
std::optional<personal_context::proto::Date> ParseDate(std::string_view str) {
  size_t sep_pos = str.find_first_of(" T");
  if (sep_pos != std::string_view::npos) {
    str = str.substr(0, sep_pos);
  }
  std::vector<std::string_view> parts = base::SplitStringPiece(
      str, "-", base::TRIM_WHITESPACE, base::SPLIT_WANT_ALL);
  if (parts.size() != 3) {
    return std::nullopt;
  }
  int y = 0, m = 0, d = 0;
  if (base::StringToInt(parts[0], &y) && base::StringToInt(parts[1], &m) &&
      base::StringToInt(parts[2], &d)) {
    personal_context::proto::Date date;
    date.set_year(y);
    date.set_month(m);
    date.set_day(d);
    return date;
  }
  return std::nullopt;
}

// Returns a `personal_context::proto::Date` extracted from `typed_val` (using
// `date()`) or parsed from `val`. Returns `std::nullopt` if no valid date can
// be obtained.
std::optional<personal_context::proto::Date> ToDate(
    const std::optional<personal_context::proto::TypedValue>& typed_val,
    std::string_view val) {
  if (typed_val && typed_val->has_date()) {
    return typed_val->date();
  }
  return ParseDate(val);
}

// Returns a `personal_context::proto::DateTime` extracted from `typed_val`
// (using `date_time()` or `date()`) or parsed from `val`. Returns
// `std::nullopt` if no valid date/time can be obtained.
std::optional<personal_context::proto::DateTime> ToDateTime(
    const std::optional<personal_context::proto::TypedValue>& typed_val,
    std::string_view val) {
  if (typed_val && typed_val->has_date_time()) {
    return typed_val->date_time();
  }
  if (std::optional<personal_context::proto::Date> date =
          ToDate(typed_val, val)) {
    personal_context::proto::DateTime date_time;
    date_time.set_year(date->year());
    date_time.set_month(date->month());
    date_time.set_day(date->day());
    return date_time;
  }
  return std::nullopt;
}

// Formats year, month, and day into "YYYY-MM-DD" ISO format.
std::u16string DateToIsoString(int year, int month, int day) {
  return base::UTF8ToUTF16(
      base::StringPrintf("%04d-%02d-%02d", year, month, day));
}

// Formats a date from `typed_value` or `fallback_str` into short "MMM d" label
// format (e.g. "Jun 7").
std::optional<std::u16string> FormatShortDate(
    const std::optional<personal_context::proto::TypedValue>& typed_value,
    std::u16string_view fallback_str = u"") {
  int year = 0;
  int month = 0;
  int day = 0;
  if (typed_value) {
    if (typed_value->has_date()) {
      year = typed_value->date().year();
      month = typed_value->date().month();
      day = typed_value->date().day();
    } else if (typed_value->has_date_time()) {
      year = typed_value->date_time().year();
      month = typed_value->date_time().month();
      day = typed_value->date_time().day();
    }
  }
  if (month == 0 && !fallback_str.empty()) {
    if (std::optional<personal_context::proto::Date> parsed_date =
            ParseDate(base::UTF16ToUTF8(fallback_str))) {
      year = parsed_date->year();
      month = parsed_date->month();
      day = parsed_date->day();
    }
  }
  if (year <= 0 || month <= 0 || month > 12 || day <= 0 || day > 31) {
    return std::nullopt;
  }
  base::Time::Exploded exploded{
      .year = year,
      .month = month,
      .day_of_month = day,
      .hour = 12,
  };
  base::Time time;
  if (base::Time::FromLocalExploded(exploded, &time)) {
    return base::LocalizedTimeFormatWithPattern(time, "MMM d");
  }
  return std::nullopt;
}

// Formats a `base::Time` time-of-day for the given `app_locale`, falling back
// to the process default locale if parsing fails.
std::u16string FormatTimeOfDay(base::Time time, std::string_view app_locale) {
  if (std::optional<base::i18n::LanguageTag> tag =
          base::i18n::GetLanguageTagFromString(app_locale)) {
    return base::i18n::IcuBridge::GetInstance().date_time_formatter().Format(
        time, *tag,
        base::i18n::datetime_options::T::Short().with_time_precision(
            base::i18n::DateTimeFormatterOptions::TimePrecision::kMinute));
  }
  return base::TimeFormatTimeOfDay(time);
}

std::u16string FormatTypedValue(
    const personal_context::proto::TypedValue& typed_value,
    std::string_view app_locale) {
  switch (typed_value.value_case()) {
    case personal_context::proto::TypedValue::kCountryCode: {
      std::u16string country_name = l10n_util::GetDisplayNameForCountry(
          typed_value.country_code(), app_locale);
      if (!country_name.empty() &&
          !base::EqualsCaseInsensitiveASCII(country_name,
                                            typed_value.country_code()) &&
          !base::EqualsCaseInsensitiveASCII(
              country_name, base::StrCat({"_", typed_value.country_code()}))) {
        return country_name;
      }
      break;
    }
    case personal_context::proto::TypedValue::kDate: {
      // TODO(crbug.com/539400547): Support localized date formatting.
      const personal_context::proto::Date& date = typed_value.date();
      return DateToIsoString(date.year(), date.month(), date.day());
    }
    case personal_context::proto::TypedValue::kDateTime: {
      // TODO(crbug.com/539400547): Support localized date formatting.
      const personal_context::proto::DateTime& date_time =
          typed_value.date_time();
      std::u16string date_str =
          DateToIsoString(date_time.year(), date_time.month(), date_time.day());
      base::Time::Exploded exploded{
          .year = date_time.year(),
          .month = date_time.month(),
          .day_of_month = date_time.day(),
          .hour = date_time.hours(),
          .minute = date_time.minutes(),
      };
      base::Time time;
      if (base::Time::FromLocalExploded(exploded, &time)) {
        return base::StrCat(
            {date_str, u" ", FormatTimeOfDay(time, app_locale)});
      }
      return date_str;
    }
    case personal_context::proto::TypedValue::kStringList:
      return base::UTF8ToUTF16(base::JoinString(
          base::ToVector<std::string_view>(typed_value.string_list().values()),
          ", "));
    case personal_context::proto::TypedValue::VALUE_NOT_SET:
      break;
  }
  return u"";
}

std::u16string FormatAttributeValue(
    const personal_context::proto::Attribute& attribute,
    std::string_view app_locale) {
  if (attribute.has_typed_value()) {
    std::u16string formatted =
        FormatTypedValue(attribute.typed_value(), app_locale);
    if (!formatted.empty()) {
      return formatted;
    }
  }
  return base::UTF8ToUTF16(attribute.value());
}

