// Parses a date string in "YYYY-MM-DD" format (such as generated by
// `SerializeDate`) into a `personal_context::proto::Date`. Returns
// `std::nullopt` if `str` is not in the expected format or cannot be parsed.
std::optional<personal_context::proto::Date> ParseDate(std::string_view str) {
  std::vector<std::string_view> parts = base::SplitStringPiece(
      str, "-", base::TRIM_WHITESPACE, base::SPLIT_WANT_ALL);
  if (parts.size() != 3) {
    return std::nullopt;
  }
  int y = 0, m = 0, d = 0;
  if (base::StringToInt(parts[0], &y) && base::StringToInt(parts[1], &m) &&
      base::StringToInt(parts[2], &d)) {
    personal_context::proto::Date date;
    date.set_year(y);
    date.set_month(m);
    date.set_day(d);
    return date;
  }
  return std::nullopt;
}

