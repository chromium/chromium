TEST(ColorProviderKeyTest, EqualityUserColor) {
  ColorProviderKey key1;
  ColorProviderKey key2;
  key1.user_color = SK_ColorRED;
  key2.user_color = std::nullopt;
  EXPECT_NE(key1, key2);

  key2.user_color = SK_ColorBLUE;
  EXPECT_NE(key1, key2);

  key2.user_color = SK_ColorRED;
  EXPECT_EQ(key1, key2);
}

