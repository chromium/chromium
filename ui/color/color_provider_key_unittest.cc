TEST(ColorProviderKeyTest, EqualityCustomTheme) {
  ColorProviderKey key1;
  ColorProviderKey key2;
  auto theme1 = base::MakeRefCounted<TestThemeInitializerSupplier>(
      ColorProviderKey::ThemeInitializerSupplier::ThemeType::kExtension);
  auto theme2 = base::MakeRefCounted<TestThemeInitializerSupplier>(
      ColorProviderKey::ThemeInitializerSupplier::ThemeType::kAutogenerated);

  key1.custom_theme = theme1;
  key2.custom_theme = nullptr;
  EXPECT_NE(key1, key2);

  key2.custom_theme = theme2;
  EXPECT_NE(key1, key2);

  key2.custom_theme = theme1;
  EXPECT_EQ(key1, key2);
}

TEST(ColorProviderKeyTest, EqualityAppController) {
  ColorProviderKey key1;
  ColorProviderKey key2;
  TestInitializerSupplier supplier1;
  TestInitializerSupplier supplier2;

  key1.app_controller = &supplier1;
  key2.app_controller = nullptr;
  EXPECT_NE(key1, key2);

  key2.app_controller = &supplier2;
  EXPECT_NE(key1, key2);

  key2.app_controller = &supplier1;
  EXPECT_EQ(key1, key2);
}

