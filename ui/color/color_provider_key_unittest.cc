class TestInitializerSupplier : public ColorProviderKey::InitializerSupplier {
 public:
  void AddColorMixers(ColorProvider* provider,
                      const ColorProviderKey& key) const override {}
};

class TestThemeInitializerSupplier
    : public ColorProviderKey::ThemeInitializerSupplier {
 public:
  explicit TestThemeInitializerSupplier(ThemeType theme_type)
      : ThemeInitializerSupplier(theme_type) {}
  void AddColorMixers(ColorProvider* provider,
                      const ColorProviderKey& key) const override {}
  bool GetColor(int id, SkColor* color) const override { return false; }
  bool GetTint(int id, color_utils::HSL* hsl) const override { return false; }
  bool GetDisplayProperty(int id, int* result) const override { return false; }
  bool HasCustomImage(int id) const override { return false; }

 protected:
  ~TestThemeInitializerSupplier() override = default;
};

TEST(ColorProviderKeyTest, EqualityDefaultKeys) {
  ColorProviderKey key1;
  ColorProviderKey key2;
  EXPECT_EQ(key1, key2);
}

