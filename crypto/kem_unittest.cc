TEST(KemTest, Mlkem768InvalidCiphertextLength) {
  auto privkey = PrivateKey::GenerateMlkem768();
  auto pubkey = PublicKey::FromPrivateKey(privkey);

  auto encap = Encapsulate(kMlkem768, pubkey);

  // Empty ciphertext
  EXPECT_FALSE(Decapsulate(kMlkem768, privkey, {}).has_value());

  // 1 byte too short
  auto short_ciphertext = encap.ciphertext;
  short_ciphertext.pop_back();
  EXPECT_FALSE(Decapsulate(kMlkem768, privkey, short_ciphertext).has_value());

  // 1 byte too long
  auto long_ciphertext = encap.ciphertext;
  long_ciphertext.push_back(0x00);
  EXPECT_FALSE(Decapsulate(kMlkem768, privkey, long_ciphertext).has_value());
}

TEST(KemTest, Mlkem768CorruptedCiphertext) {
  auto privkey = PrivateKey::GenerateMlkem768();
  auto pubkey = PublicKey::FromPrivateKey(privkey);

  auto encap = Encapsulate(kMlkem768, pubkey);

  // ML-KEM uses implicit rejection: decapsulating a modified ciphertext returns
  // a pseudorandom secret that does NOT match the original encapsulated secret.
  auto corrupted_ciphertext = encap.ciphertext;
  corrupted_ciphertext[0] ^= 0xFF;

  auto decap = Decapsulate(kMlkem768, privkey, corrupted_ciphertext);
  ASSERT_TRUE(decap.has_value());
  EXPECT_NE(*decap, encap.secret);
}

TEST(KemTest, Mlkem768WrongPrivateKey) {
  auto privkey1 = PrivateKey::GenerateMlkem768();
  auto pubkey1 = PublicKey::FromPrivateKey(privkey1);
  auto privkey2 = PrivateKey::GenerateMlkem768();

  auto encap = Encapsulate(kMlkem768, pubkey1);

  // Decapsulating with a different private key will hit the implicit rejection
  // mentioned in the previous test case.
  auto decap = Decapsulate(kMlkem768, privkey2, encap.ciphertext);
  ASSERT_TRUE(decap.has_value());
  EXPECT_NE(*decap, encap.secret);
}

TEST(KemTest, WrongKeyTypeDeath) {
  auto ec_priv = PrivateKey::GenerateEcP256();
  auto ec_pub = PublicKey::FromPrivateKey(ec_priv);

  auto mlkem_priv = PrivateKey::GenerateMlkem768();
  auto mlkem_pub = PublicKey::FromPrivateKey(mlkem_priv);

  auto encap = Encapsulate(kMlkem768, mlkem_pub);

  EXPECT_CHECK_DEATH(Encapsulate(kMlkem768, ec_pub));
  EXPECT_CHECK_DEATH(Decapsulate(kMlkem768, ec_priv, encap.ciphertext));
}

