TEST(KemTest, Mlkem768RoundTrip) {
  auto privkey = PrivateKey::GenerateMlkem768();
  auto pubkey = PublicKey::FromPrivateKey(privkey);

  auto encap = Encapsulate(kMlkem768, pubkey);
  EXPECT_EQ(encap.ciphertext.size(), 1088u);
  EXPECT_EQ(encap.secret.size(), 32u);

  auto decap = Decapsulate(kMlkem768, privkey, encap.ciphertext);
  ASSERT_TRUE(decap.has_value());
  EXPECT_EQ(*decap, encap.secret);
}

TEST(KemTest, Mlkem768MultipleEncapsulations) {
  auto privkey = PrivateKey::GenerateMlkem768();
  auto pubkey = PublicKey::FromPrivateKey(privkey);

  auto encap1 = Encapsulate(kMlkem768, pubkey);
  auto encap2 = Encapsulate(kMlkem768, pubkey);

  EXPECT_NE(encap1.ciphertext, encap2.ciphertext);
  EXPECT_NE(encap1.secret, encap2.secret);

  auto decap1 = Decapsulate(kMlkem768, privkey, encap1.ciphertext);
  auto decap2 = Decapsulate(kMlkem768, privkey, encap2.ciphertext);

  ASSERT_TRUE(decap1.has_value());
  ASSERT_TRUE(decap2.has_value());
  EXPECT_EQ(*decap1, encap1.secret);
  EXPECT_EQ(*decap2, encap2.secret);
}

