// Per the WebXR spec, the OS should treat the content generated by the page
// as sRGB, so we request/only support the sRGB format from the runtime.
constexpr int64_t kSwapchainFormat = GL_SRGB8_ALPHA8;
constexpr float kStereoEyeUvWidth = 0.5f;

struct OpenGLESLayerData : public OpenXrCompositionLayer::GraphicsBindingData {
  OpenGLESLayerData() { type = kOpenGLES; }
  ~OpenGLESLayerData() override {
    if (back_buffer_fbo) {
      glDeleteFramebuffersEXT(1, &back_buffer_fbo);
    }
  }

  GLuint back_buffer_fbo = 0;
  bool using_shared_images = false;
};

OpenGLESLayerData& GetOpenGLESLayerData(OpenXrCompositionLayer& layer) {
  OpenGLESLayerData* data =
      static_cast<OpenGLESLayerData*>(layer.graphics_binding_data());
  // Layers are always created by OpenXrGraphicsBindingOpenGLES so this
  // should be safe.
  CHECK(data);
  CHECK(data->type == OpenXrCompositionLayer::GraphicsBindingData::kOpenGLES);
  return *data;
}

