package org.chromium.bytecode;

import static org.objectweb.asm.Opcodes.ACC_FINAL;
import static org.objectweb.asm.Opcodes.ACC_PROTECTED;
import static org.objectweb.asm.Opcodes.ACC_PUBLIC;
import static org.objectweb.asm.Opcodes.ASM9;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.MethodVisitor;

import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Checks which traced methods a class already declares and which ones can be overridden from a
 * superclass. Callers must pre-filter classes to exclude abstract/interface classes and check
 * {@link #shouldTraceClass} before visiting.
 *
 * <p>For each method provided in {@code methodsToCheck}: if the class declares the method, we can
 * rewrite it directly; otherwise we walk superclasses via {@link ParentCache} to determine whether
 * an override can be generated by {@link EmptyOverrideGeneratorClassAdapter} (skipping private,
 * final, package-private, or absent parent methods).
 *
 * <p>This adapter modifies the provided method list to indicate which methods should be overridden
 * or skipped.
 */
class MethodCheckerClassAdapter extends ClassVisitor {
    private static final String VIEW_CLASS_DESCRIPTOR = "android/view/View";
    private static final String ANIMATOR_UPDATE_LISTENER_CLASS_DESCRIPTOR =
            "android/animation/ValueAnimator$AnimatorUpdateListener";
    private static final String ANIMATOR_LISTENER_CLASS_DESCRIPTOR =
            "android/animation/Animator$AnimatorListener";

    /** Caches method overridability per parent class across subclasses and worker threads. */
    static final class ParentCache {
        private static final class ParentClassInfo {
            static final ParentClassInfo MISSING =
                    new ParentClassInfo(null, Collections.emptyMap());

            final String mSuperName;
            // Maps "name + descriptor" -> true if method is public or protected and non-final.
            final Map<String, Boolean> mOverridableByMethod;

            ParentClassInfo(String superName, Map<String, Boolean> overridableByMethod) {
                mSuperName = superName;
                mOverridableByMethod = overridableByMethod;
            }
        }

        private final ClassHierarchy mClassHierarchy;
        private final ConcurrentHashMap<String, ParentClassInfo> mCache = new ConcurrentHashMap<>();

        ParentCache(ClassHierarchy classHierarchy) {
            mClassHierarchy = classHierarchy;
        }

        private ParentClassInfo get(String className) {
            return mCache.computeIfAbsent(className, this::load);
        }

        private ParentClassInfo load(String className) {
            byte[] bytes = mClassHierarchy.getClassBytes(className);
            if (bytes == null) {
                return ParentClassInfo.MISSING;
            }
            ClassReader cr = new ClassReader(bytes);
            Map<String, Boolean> overridableByMethod = new HashMap<>();
            cr.accept(
                    new ClassVisitor(ASM9) {
                        @Override
                        public MethodVisitor visitMethod(
                                int access,
                                String name,
                                String descriptor,
                                String signature,
                                String[] exceptions) {
                            boolean isOverridable =
                                    (access & (ACC_PUBLIC | ACC_PROTECTED)) != 0
                                            && (access & ACC_FINAL) == 0;
                            overridableByMethod.put(name + descriptor, isOverridable);
                            return null;
                        }
                    },
                    ClassReader.SKIP_CODE | ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);
            return new ParentClassInfo(cr.getSuperName(), overridableByMethod);
        }
    }

    private final ArrayList<MethodDescription> mMethodsToCheck;
    private final ParentCache mParentCache;
    private String mSuperName;

    public MethodCheckerClassAdapter(
            ArrayList<MethodDescription> methodsToCheck, ParentCache parentCache) {
        super(ASM9);
        mMethodsToCheck = methodsToCheck;
        mParentCache = parentCache;
    }

    @Override
    public void visit(
            int version,
            int access,
            String name,
            String signature,
            String superName,
            String[] interfaces) {
        mSuperName = superName;
    }

    @Override
    public MethodVisitor visitMethod(
            int access, String name, String descriptor, String signature, String[] exceptions) {
        for (MethodDescription method : mMethodsToCheck) {
            if (method.methodName.equals(name) && method.description.equals(descriptor)) {
                method.shouldCreateOverride = false;
            }
        }
        return null;
    }

    @Override
    public void visitEnd() {
        for (MethodDescription method : mMethodsToCheck) {
            if (method.shouldCreateOverride == null) {
                checkParentClass();
                return;
            }
        }
    }

    static boolean shouldTraceClass(String desc, ClassHierarchy classHierarchy) {
        return classHierarchy.isAssignableFrom(VIEW_CLASS_DESCRIPTOR, desc)
                || classHierarchy.isAssignableFrom(ANIMATOR_UPDATE_LISTENER_CLASS_DESCRIPTOR, desc)
                || classHierarchy.isAssignableFrom(ANIMATOR_LISTENER_CLASS_DESCRIPTOR, desc);
    }

    private void checkParentClass() {
        String cur = mSuperName;
        while (cur != null && !"java/lang/Object".equals(cur)) {
            ParentCache.ParentClassInfo info = mParentCache.get(cur);
            if (info == ParentCache.ParentClassInfo.MISSING) {
                // Skip tracing classes with missing superclasses to avoid generating overrides or
                // failing frame computation on incomplete hierarchies.
                mMethodsToCheck.clear();
                return;
            }
            boolean anyUnchecked = false;
            for (MethodDescription method : mMethodsToCheck) {
                if (method.shouldCreateOverride != null) {
                    continue;
                }
                Boolean overridable =
                        info.mOverridableByMethod.get(method.methodName + method.description);
                if (overridable != null) {
                    method.shouldCreateOverride = overridable;
                } else {
                    anyUnchecked = true;
                }
            }
            if (!anyUnchecked) {
                return;
            }
            cur = info.mSuperName;
        }
        // We support tracing methods that are defined in classes that are derived from View,
        // but are not defined in View itself. If we've reached Object, the method doesn't
        // exist in this hierarchy, so don't override it.
        for (MethodDescription method : mMethodsToCheck) {
            if (method.shouldCreateOverride == null) {
                method.shouldCreateOverride = false;
            }
        }
    }
}
