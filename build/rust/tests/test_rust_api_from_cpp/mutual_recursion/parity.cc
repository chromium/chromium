#include "build/rust/tests/test_rust_api_from_cpp/mutual_recursion/parity.h"

#include "build/rust/tests/test_rust_api_from_cpp/mutual_recursion/is_odd.h"

namespace parity {

bool IsEven(int n) {
  if (n == 0) {
    return true;
  }
  return IsOdd(n - 1);
}

// This test simulates that `IsOdd` used to be implemented in C++ as:
//
//   if (n == 0) {
//     return false;
//   }
//   return IsEven(n - 1);
//
// and has been rewritten in Rust (see `is_odd.rs`).  The C++ definition below
// forwards to Rust, through the C++ API generated by `cpp_api_from_rust` for
// the `:is_odd` crate (`is_odd.h`).  C++ callers still call `parity::IsOdd`,
// and don't need to change.
//
// TODO(lukasza): Research if this small C++ function can be avoided - e.g. if
// `parity::IsOdd` can be implemented directly in Rust (in the `parity`
// namespace, rather than in a separate `is_odd` namespace).
bool IsOdd(int n) {
  return is_odd::is_odd(n);
}

}  // namespace parity
