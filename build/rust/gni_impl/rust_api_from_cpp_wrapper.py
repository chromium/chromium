import argparse
import json
import os
import pathlib
import shlex
import subprocess
import sys

from filter_clang_args import filter_clang_args


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        '--rust-api-from-cpp-exe-path', required=True, type=pathlib.Path
    )
    parser.add_argument('--flagfile-path', required=True, type=pathlib.Path)
    parser.add_argument(
        '--target-args-path',
        required=True,
        type=pathlib.Path,
        help='JSON file (generated by GN) with the value of `--target_args`',
    )
    parser.add_argument(
        'args',
        metavar='ARG',
        nargs='+',
        help='`--foo=bar` flags of `rs_bindings_from_cc`, then `--`, '
        'and then Clang args',
    )
    args = parser.parse_args()

    clang_split_index = args.args.index('--')
    generator_args = args.args[:clang_split_index]
    clang_args = filter_clang_args(args.args[clang_split_index + 1 :])

    if 'CRUBIT_DEBUG' in os.environ:
        generator_args.append(
            f'--ir_out={args.flagfile_path.with_suffix(".ir")}'
        )

    with open(args.target_args_path, 'r') as f:
        target_args = json.load(f)
    generator_args.append(f'--target_args={json.dumps(target_args)}')

    # Long cmdlines may not work - work around that by using Abseil's
    # `--flagfile` (see also
    # https://abseil.io/docs/python/guides/flags#a-note-about---flagfile).
    #
    # Note that `clang_args` are not written to the flag file, because Abseil's
    # flag parsing code is only aware of `ABSL_FLAG`-declared flags and doesn't
    # know about Clang args (e.g. `-W...` or `-I...`).
    with open(args.flagfile_path, 'w') as f:
        for line in generator_args:
            print(line, file=f)

    cmdline = [
        str(args.rust_api_from_cpp_exe_path),
        f'--flagfile={args.flagfile_path}',
        '--',
        *clang_args,
    ]
    if 'CRUBIT_DEBUG' in os.environ:
        print(f'CRUBIT_DEBUG: CMDLINE: {shlex.join(cmdline)}', file=sys.stderr)

    return subprocess.run(cmdline, check=False).returncode


if __name__ == '__main__':
    sys.exit(main())
