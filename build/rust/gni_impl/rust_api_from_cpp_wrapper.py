import argparse
import json
import os
import pathlib
import shlex
import subprocess
import sys

from filter_clang_args import filter_clang_args

# Characters special to LLVM's `TokenizeGNUCommandLine` in `@<file>` response
# files.
_RESPONSE_FILE_ESCAPE_TRANSLATION = str.maketrans(
    {
        '\\': '\\\\',
        '"': '\\"',
        "'": "\\'",
        ' ': '\\ ',
        '\t': '\\\t',
        '\r': '\\\r',
        '\n': '\\\n',
    }
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        '--rust-api-from-cpp-exe-path', required=True, type=pathlib.Path
    )
    parser.add_argument('--flagfile-path', required=True, type=pathlib.Path)
    parser.add_argument(
        '--target-args-path',
        required=True,
        type=pathlib.Path,
        help='JSON file (generated by GN) with the value of `--target_args`',
    )
    # TODO(https://crbug.com/587508854): Remove after the Crubit roll lands and
    # `rust_api_from_cpp.gni` stops passing `--use-legacy-abseil-flagfile`.
    parser.add_argument(
        '--use-legacy-abseil-flagfile',
        action='store_true',
        help=(
            'Use Abseil `--flagfile=` instead of an LLVM `@<file>` response '
            'file'
        ),
    )
    parser.add_argument(
        'args',
        metavar='ARG',
        nargs='+',
        help='`--foo=bar` flags of `rs_bindings_from_cc`, then `--`, '
        'and then Clang args',
    )
    args = parser.parse_args()

    clang_split_index = args.args.index('--')
    generator_args = args.args[:clang_split_index]
    clang_args = filter_clang_args(args.args[clang_split_index + 1 :])

    if 'CRUBIT_DEBUG' in os.environ:
        generator_args.append(
            f'--ir_out={args.flagfile_path.with_suffix(".ir")}'
        )

    with open(args.target_args_path, 'r', encoding='utf-8') as f:
        target_args = json.load(f)
    generator_args.append(f'--target_args={json.dumps(target_args)}')

    if args.use_legacy_abseil_flagfile:
        # See TODO above definition of `--use-legacy-abseil-flagfile`.
        with open(args.flagfile_path, 'w', encoding='utf-8') as f:
            for line in generator_args:
                print(line, file=f)
        flagfile_arg = f'--flagfile={args.flagfile_path}'
    else:
        # Long cmdlines may not work - work around that by writing Crubit flags
        # to an `@<file>` response file, one argument per `\n`-terminated line
        # with characters special to LLVM's `TokenizeGNUCommandLine` escaped.
        # `newline='\n'` prevents Python on Windows from translating `\n`
        # (including escaped newlines) into `\r\n`.
        with open(args.flagfile_path, 'w', encoding='utf-8', newline='\n') as f:
            for arg in generator_args:
                f.write(arg.translate(_RESPONSE_FILE_ESCAPE_TRANSLATION) + '\n')
        flagfile_arg = f'@{args.flagfile_path}'

    cmdline = [
        str(args.rust_api_from_cpp_exe_path),
        flagfile_arg,
        '--',
        *clang_args,
    ]
    if 'CRUBIT_DEBUG' in os.environ:
        print(f'CRUBIT_DEBUG: CMDLINE: {shlex.join(cmdline)}', file=sys.stderr)

    return subprocess.run(cmdline, check=False).returncode


if __name__ == '__main__':
    sys.exit(main())
