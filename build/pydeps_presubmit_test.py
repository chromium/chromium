import os
import subprocess
import sys
import unittest

sys.path.append(os.path.join(os.path.dirname(__file__), '..'))

import pydeps_presubmit
from PRESUBMIT_test_mocks import MockAffectedFile, MockInputApi, MockOutputApi


class PydepsPresubmitTest(unittest.TestCase):
    class _MockPopen:
        def __init__(self, stdout='', stderr='', returncode=0):
            self.stdout = stdout.encode('utf-8')
            self.stderr = stderr.encode('utf-8')
            self.returncode = returncode

        def communicate(self, input=None):
            return (self.stdout, self.stderr)

    class _MockSubprocess:
        CalledProcessError = subprocess.CalledProcessError
        PIPE = 0

        def __init__(self):
            self._popen_func = None

        def SetPopenCallback(self, func):
            self._popen_func = func

        def Popen(self, cmd, *args, **kwargs):
            res = self._popen_func(cmd)
            if isinstance(res, tuple):
                returncode, stdout, stderr = res
                return PydepsPresubmitTest._MockPopen(
                    stdout=stdout, stderr=stderr, returncode=returncode
                )
            return PydepsPresubmitTest._MockPopen(stdout=res)

    def _MockParseGclientArgs(self, is_android=True):
        return lambda: {'checkout_android': 'true' if is_android else 'false'}

    def setUp(self):
        self.mock_all_pydeps = ['A.pydeps', 'B.pydeps', 'D.pydeps']
        self.mock_android_pydeps = ['D.pydeps']
        self.mock_generic_pydeps = ['A.pydeps', 'B.pydeps']
        self.old_ParseGclientArgs = pydeps_presubmit._ParseGclientArgs
        pydeps_presubmit._ParseGclientArgs = self._MockParseGclientArgs()
        self.mock_input_api = MockInputApi()
        self.mock_input_api.platform = 'linux'
        self.mock_input_api.presubmit_local_path = (
            self.mock_input_api.change.RepositoryRoot()
        )
        self.mock_output_api = MockOutputApi()
        self.checker = pydeps_presubmit.PydepsChecker(
            self.mock_input_api, self.mock_all_pydeps
        )
        self.mock_input_api.subprocess = PydepsPresubmitTest._MockSubprocess()
        self.checker._file_cache = {
            'A.pydeps': (
                '# Generated by:\n# CMD --output A.pydeps A\nA.py\nC.py\n'
            ),
            'B.pydeps': (
                '# Generated by:\n# CMD --output B.pydeps B\nB.py\nC.py\n'
            ),
            'D.pydeps': '# Generated by:\n# CMD --output D.pydeps D\nD.py\n',
        }

    def tearDown(self):
        pydeps_presubmit._ParseGclientArgs = self.old_ParseGclientArgs

    def _RunCheck(self):
        return pydeps_presubmit.run_presubmit(
            self.mock_input_api,
            self.mock_output_api,
            all_pydeps_files=self.mock_all_pydeps,
            android_specific_pydeps_files=self.mock_android_pydeps,
            generic_pydeps_files=self.mock_generic_pydeps,
            checker_for_tests=self.checker,
        )

    def testAddedPydep(self):
        self.mock_input_api.InitFiles(
            [
                MockAffectedFile('new.pydeps', [], action='A'),
            ]
        )

        results = self._RunCheck()
        self.assertEqual(1, len(results))
        self.assertIn('PYDEPS_FILES', str(results[0]))

    def testPydepNotInSrc(self):
        self.mock_input_api.InitFiles(
            [
                MockAffectedFile('new.pydeps', [], action='A'),
            ]
        )
        self.mock_input_api.os_path.exists = lambda x: False
        results = self._RunCheck()
        self.assertEqual(0, len(results))

    def testRemovedPydep(self):
        self.mock_input_api.InitFiles(
            [
                MockAffectedFile(self.mock_all_pydeps[0], [], action='D'),
            ]
        )
        results = self._RunCheck()
        self.assertEqual(1, len(results))
        self.assertIn('PYDEPS_FILES', str(results[0]))

    def testRandomPyIgnored(self):
        self.mock_input_api.files = [
            MockAffectedFile('random.py', []),
        ]

        results = self._RunCheck()
        self.assertEqual(0, len(results), 'Unexpected results: %r' % results)

    def testPresubmitPyIgnored(self):
        self.mock_input_api.files = [
            MockAffectedFile('PRESUBMIT.py', []),
            MockAffectedFile('PRESUBMIT_test.py', []),
        ]
        self.mock_input_api.subprocess.SetPopenCallback(
            lambda cmd: self.fail(f'Unexpected command execution: {cmd!r}')
        )

        self.assertEqual(set(), self.checker.ComputeAffectedPydeps())
        results = self._RunCheck()
        self.assertEqual(0, len(results), 'Unexpected results: %r' % results)

