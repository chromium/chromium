#ifndef BASE_I18N_TAGS_H_
#define BASE_I18N_TAGS_H_

#include <functional>
#include <string_view>

#include "base/containers/fixed_flat_set.h"
#include "base/i18n/internal/bcp47_parser.h"
#include "base/i18n/language_tag.h"
#include "base/no_destructor.h"

// This file provides access to compile-time validated, canonical `LanguageTag`
// constants for the most commonly used locales in Chromium.
//
// A consteval base::i18n::GetKnownLanguageTag(std::string_view tag) function is
// offered. The function is marked as consteval so we can safely fail
// compilation if the tag is not known and also have the user not need to check
// an optional return.
//
// Usage:
//   constexpr base::i18n::LanguageTag en =
//       base::i18n::GetKnownLanguageTag("en");
//   constexpr base::i18n::LanguageTag zh_cn =
//       base::i18n::GetKnownLanguageTag("zh-CN");
//
// If the function is called with a unknown tag, the code does not compile.
// Notice that not being able to use GetKnownLanguageTag<> does not mean the tag
// is not valid.
//
// Compilation error example:
//   // The tag "en-BR" is valid, but it is not pre-defined in our list of known
//   // chromium tags.
//   constexpr base::i18n::LanguageTag en =
//       base::i18n::GetKnownLanguageTag("en-BR");
//
//
// The list of supported languages is generated by the action
// `canonical_language_tags_gen` and stored in
// `base/i18n/internal/canonical_language_tags.inc`.
namespace base::i18n {

// Returns a LanguageTag checked at compile time. does not compile if tag is
// not one of the predefined supported language tags.
consteval LanguageTag GetKnownLanguageTag(std::string_view tag) {
  std::optional<i18n_internal::ParsedBcp47Tag> parsed =
      i18n_internal::ParseBcp47Tag(tag);
  if (!parsed) {
    void ERROR_TagIsMalformed();
    ERROR_TagIsMalformed();
  }

  if (!i18n_internal::AreSubtagsKnown(*parsed)) {
    void ERROR_TagIsUnknown();
    ERROR_TagIsUnknown();
  }

  // It is only possible to construct `LanguageTag`s at compile-time if they
  // are small.
  if (tag.size() > i18n_internal::ImmutableString::kSmallBufferSize) {
    void ERROR_TagIsTooLarge();
    ERROR_TagIsTooLarge();
  }

  return LanguageTag(base::span<const std::string_view>({tag}));
}

}  // namespace base::i18n

#endif  // BASE_I18N_TAGS_H_
