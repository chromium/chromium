import {gCrWeb, setRegisterCallback} from '//ios/web/public/js_messaging/resources/gcrweb.js';
import {generateRandomId, sendWebKitMessage} from '//ios/web/public/js_messaging/resources/utils.js';

interface RegisteredChild {
  window: WeakRef<WindowProxy>;
  element: WeakRef<HTMLIFrameElement|HTMLObjectElement>|null;
}

const PARENT_CHILD_TOKEN_SYMBOL = Symbol('parentChildToken');
const REGISTERED_CHILDREN_SYMBOL = Symbol('registeredChildren');

declare global {
  interface Window {
    [PARENT_CHILD_TOKEN_SYMBOL]?: string;
    [REGISTERED_CHILDREN_SYMBOL]?: Map<string, RegisteredChild>;
  }
}

// Unique token generated for this frame to identify the parent-child
// relationship between this frame and its parent frame. It must not be leaked
// to the content world. Re-used if the script is reinjected (e.g.
// document.open()).
if (!window[PARENT_CHILD_TOKEN_SYMBOL]) {
  window[PARENT_CHILD_TOKEN_SYMBOL] = generateRandomId();
}
const parentChildToken = window[PARENT_CHILD_TOKEN_SYMBOL]!;

// Secret string replaced by C++ ($(SECRET)) that is only known to scripts
// running in the isolated world. It must not be leaked to the content world.
// Used to guarantee that the registration message sent via postMessage between
// frames was sent from the isolated world.
const ISOLATED_WORLD_SECRET = '$(SECRET)';

// Map of registered child frames. Re-used if the script is reinjected.
if (!window[REGISTERED_CHILDREN_SYMBOL]) {
  window[REGISTERED_CHILDREN_SYMBOL] = new Map<string, RegisteredChild>();
}
const registeredChildren = window[REGISTERED_CHILDREN_SYMBOL]!;

/**
 * Finds the HTML iframe or object element corresponding to the given window
 * proxy.
 * @param source The WindowProxy of the child frame.
 * @return The iframe or object element in the current document, or null if not
 *     found.
 */
function findFrameElement(source: WindowProxy): HTMLIFrameElement|
    HTMLObjectElement|null {
  const iframes = document.getElementsByTagName('iframe');
  for (let i = 0; i < iframes.length; i++) {
    const iframe = iframes[i];
    if (iframe && iframe.contentWindow === source) {
      return iframe;
    }
  }
  const objects = document.getElementsByTagName('object');
  for (let i = 0; i < objects.length; i++) {
    const obj = objects[i];
    if (obj && obj.contentWindow === source) {
      return obj;
    }
  }
  return null;
}

/**
 * Registers a child frame by storing its WindowProxy and element reference,
 * and sends a message to C++ with the parent-child relationship token.
 * @param source The WindowProxy of the child frame registering itself.
 * @param parentChildToken The unique token generated by the child frame.
 * @param receivedSecret The secret sent by the child frame to authenticate the
 *     request.
 */
function registerChildFrame(
    source: any, parentChildToken: string, receivedSecret: string) {
  if (receivedSecret !== ISOLATED_WORLD_SECRET) {
    return;
  }
  if (!source || source.parent !== window) {
    return;
  }

  // Remove any previous association for this window element (e.g. if the
  // subframe navigated), or any stale entries whose window was garbage
  // collected.
  for (const [childToken, registeredChild] of registeredChildren.entries()) {
    const win = registeredChild.window.deref();
    if (!win || win === source) {
      registeredChildren.delete(childToken);
      if (win === source) {
        break;
      }
    }
  }

  const element = findFrameElement(source);
  registeredChildren.set(parentChildToken, {
    window: new WeakRef(source),
    element: element ? new WeakRef(element) : null,
  });

  sendWebKitMessage('FrameChildRegistration', {
    'crwFrameId': gCrWeb.getFrameId(),
    'crwParentChildToken': parentChildToken,
  });
}

setRegisterCallback((payload: any) => {
  payload['crwParentChildToken'] = parentChildToken;
  // Only subframes need to register with their parent frame. Main frames do not
  // have a parent frame.
  // If window does not have a parent (e.g. is top frame), window.parent will
  // point to window and lead to infinite loops.
  if (window.parent !== window) {
    window.parent.postMessage(
        {
          type: 'org.chromium.registerChildFrame',
          parentChildToken: parentChildToken,
          secret: ISOLATED_WORLD_SECRET,
        },
        '*');
  }
});

window.addEventListener('message', function(event: MessageEvent) {
  const payload = event.data;
  if (!payload || typeof payload !== 'object') {
    return;
  }
  if (payload.hasOwnProperty('type')) {
    if (payload.type === 'org.chromium.registerChildFrame') {
      // Stop propagation to prevent the message and secret from leaking to
      // scripts running in the page (content world).
      event.stopPropagation();
      event.stopImmediatePropagation();
      registerChildFrame(
          event.source, payload.parentChildToken, payload.secret);
    }
  }
}, /*useCapture=*/ true);
