"""Generates the localize-strings plist and ObjC++ accessors at build time.

Invoked by //ios/chrome/credential_provider_extension:generate_localized_strings
to keep credential_provider_extension_localize_strings_config.plist,
generated_localized_strings.h, and generated_localized_strings.mm synchronized
with strings/ios_credential_provider_extension_strings.grd.

To add a new string to the Credential Provider Extension:
1) Add the <message> entry to
   strings/ios_credential_provider_extension_strings.grd and add screenshots
   (see docs/translation_screenshots.md).
2) Import generated_localized_strings.h (from
   ios/chrome/credential_provider_extension/) and call the generated accessor
   (e.g. IDS_IOS_MY_STRING_NAME -> MyStringNameString()).
"""

from __future__ import annotations

import argparse
from collections.abc import Sequence
import os
import plistlib
import sys
import tempfile
import xml.etree.ElementTree as ET

HEADER_GUARD = (
    'IOS_CHROME_CREDENTIAL_PROVIDER_EXTENSION_GENERATED_LOCALIZED_STRINGS_H_'
)
HEADER_IMPORT_PATH = (
    'ios/chrome/credential_provider_extension/generated_localized_strings.h'
)
STRINGS_GRIT_HEADER = (
    'ios/credential_provider_extension/grit/'
    'ios_credential_provider_extension_strings.h'
)
LICENSE_HEADER = """// Copyright 2025 The Chromium Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.
"""
AUTOGENERATED_NOTE = """
// NOTE: THIS FILE IS AUTOGENERATED AT BUILD TIME. DO NOT MODIFY MANUALLY.
// Generated by
// //ios/chrome/credential_provider_extension:generate_localized_strings.
"""
PREFIX_TO_REMOVE = 'IDS_IOS_'


def snake_to_camel(snake_str: str) -> str:
    """Converts snake_case to CamelCase, strips prefix, and ensures "String"."""
    if snake_str.startswith(PREFIX_TO_REMOVE):
        cleaned_str = snake_str[len(PREFIX_TO_REMOVE) :]
    else:
        cleaned_str = snake_str

    components = cleaned_str.split('_')
    camel_name = ''.join(word.capitalize() for word in components)

    if not camel_name.endswith('String'):
        camel_name += 'String'

    return camel_name


def extract_strings_from_grd(grd_filepath: str) -> Sequence[str]:
    """Extracts and validates IDS_* message names from a .grd file."""
    tree = ET.parse(grd_filepath)
    root = tree.getroot()
    # ET.parse reads only the top-level .grd without expanding .grdp includes
    # or evaluating <if> conditions, so fail fast if either appears.
    if root.findall('.//part'):
        raise ValueError(
            f'Unsupported <part> element in {grd_filepath}; '
            'generate_localized_strings.py does not expand .grdp includes'
        )
    if root.findall('.//if'):
        raise ValueError(
            f'Unsupported <if> element in {grd_filepath}; '
            'generate_localized_strings.py does not evaluate <if> conditions'
        )

    extracted_strings = []
    seen_ids = set()
    seen_funcs = {}
    for msg in root.findall('.//message'):
        name = msg.get('name')
        if not name or not name.startswith('IDS_'):
            continue
        # Reject duplicate IDs, invalid ObjC++ identifiers, or accessor
        # collisions at build time rather than emitting broken Objective-C++.
        if name in seen_ids:
            raise ValueError(f'Duplicate message ID in {grd_filepath}: {name}')
        func_name = snake_to_camel(name)
        if not (func_name.isascii() and func_name.isidentifier()):
            raise ValueError(
                f'Invalid accessor name ({func_name}) derived from {name} '
                f'in {grd_filepath}'
            )
        existing_id = seen_funcs.get(func_name)
        if existing_id is not None:
            raise ValueError(
                f'Accessor name collision ({func_name}) in {grd_filepath}: '
                f'{existing_id} vs {name}'
            )
        seen_ids.add(name)
        seen_funcs[func_name] = name
        extracted_strings.append(name)

    if not extracted_strings:
        raise ValueError(f'No IDS_* <message> entries found in {grd_filepath}')
    return extracted_strings


def write_file_if_changed(filepath: str, content: bytes | str) -> None:
    """Atomically writes `content` to `filepath`, skipping unchanged files."""
    data = content.encode('utf-8') if isinstance(content, str) else content
    # Preserve mtime when unchanged so Ninja's restat=1 prunes downstream steps.
    if os.path.exists(filepath):
        with open(filepath, 'rb') as f:
            if f.read() == data:
                return

    dir_name = os.path.dirname(filepath) or '.'
    os.makedirs(dir_name, exist_ok=True)
    tmp_path = None
    try:
        # Write in the destination directory so os.replace() stays atomic on
        # the same filesystem even if the build is interrupted mid-write.
        with tempfile.NamedTemporaryFile(
            mode='wb',
            prefix='.tempfile.',
            suffix='.' + os.path.basename(filepath),
            dir=dir_name,
            delete=False,
        ) as f:
            tmp_path = f.name
            f.write(data)
        os.replace(tmp_path, filepath)
        tmp_path = None
    finally:
        if tmp_path is not None and os.path.exists(tmp_path):
            os.unlink(tmp_path)


def generate_plist_file(
    strings_array: Sequence[str], plist_filepath: str
) -> None:
    """Writes the generate_localizable_strings config plist."""
    plist_data = {
        'headers': [STRINGS_GRIT_HEADER],
        'outputs': [
            {'name': 'Localizable.strings', 'strings': list(strings_array)}
        ],
    }
    write_file_if_changed(plist_filepath, plistlib.dumps(plist_data))


def generate_accessor_files(
    localized_strings: Sequence[str],
    header_filepath: str,
    source_filepath: str,
) -> None:
    """Writes generated_localized_strings.{h,mm} for localized_strings."""
    header_content = [
        LICENSE_HEADER,
        f'#ifndef {HEADER_GUARD}\n#define {HEADER_GUARD}\n',
        '#import <Foundation/Foundation.h>\n',
        AUTOGENERATED_NOTE,
        '\n// clang-format off\n',
    ]

    source_content = [
        LICENSE_HEADER,
        f'#import "{HEADER_IMPORT_PATH}"\n',
        AUTOGENERATED_NOTE,
        '\n// clang-format off\n',
    ]

    for original_string in localized_strings:
        func_name = snake_to_camel(original_string)
        header_content.append(f'NSString* {func_name}();\n')

        source_content.append(f'NSString* {func_name}() {{\n')
        source_content.append(
            f'  return NSLocalizedString(@"{original_string}", @"");\n'
        )
        source_content.append('}\n\n')

    header_content.append('// clang-format on\n')
    header_content.append(f'\n#endif  // {HEADER_GUARD}\n')

    source_content.append('// clang-format on\n')

    write_file_if_changed(header_filepath, ''.join(header_content))
    write_file_if_changed(source_filepath, ''.join(source_content))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description='Generates localize-strings plist and ObjC++ accessors.'
    )
    parser.add_argument(
        '--grd',
        required=True,
        help='Path to ios_credential_provider_extension_strings.grd.',
    )
    parser.add_argument(
        '--plist-out',
        required=True,
        help='Output path for the localize-strings config plist.',
    )
    parser.add_argument(
        '--header-out',
        required=True,
        help='Output path for generated_localized_strings.h.',
    )
    parser.add_argument(
        '--source-out',
        required=True,
        help='Output path for generated_localized_strings.mm.',
    )
    args = parser.parse_args(argv)

    try:
        strings = extract_strings_from_grd(args.grd)
    except (ET.ParseError, OSError, ValueError) as exc:
        print(f'Error: {exc}', file=sys.stderr)
        return 1

    generate_plist_file(strings, args.plist_out)
    generate_accessor_files(strings, args.header_out, args.source_out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
