// This must be kept in sync with the SystemTheme enum in
// ui/color/system_theme.h.
export enum SystemTheme {
  // Either classic or web theme.
  DEFAULT = 0,
  // <if expr="is_linux">
  GTK = 1,
  QT = 2,
  // </if>
}

function normalizePageVisibility(
    visibility: boolean|AppearancePageVisibility|
    undefined): AppearancePageVisibility {
  if (visibility === undefined) {
    return {
      bookmarksBar: true,
      homeButton: true,
      hoverCard: true,
      pageZoom: true,
      setTheme: true,
      sidePanel: true,
    };
  }

  if (typeof visibility === 'boolean') {
    return {
      bookmarksBar: visibility,
      homeButton: visibility,
      hoverCard: visibility,
      pageZoom: visibility,
      setTheme: visibility,
      sidePanel: visibility,
    };
  }

  return visibility;
}

