/**
 * This is the absolute difference maintained between standard and
 * fixed-width font sizes. http://crbug.com/40608310.
 */
const SIZE_DIFFERENCE_FIXED_STANDARD: number = 3;

/**
 * ID for autogenerated themes. Should match
 * |ThemeService::kAutogeneratedThemeID|.
 */
const AUTOGENERATED_THEME_ID: string = 'autogenerated_theme_id';
/**
 * ID for user color themes. Should match
 * |ThemeService::kUserColorThemeID|.
 */
const USER_COLOR_THEME_ID: string = 'user_color_theme_id';

/**
 * 'settings-appearance-page' is the settings page containing appearance
 * settings.
 */

export interface SettingsAppearancePageElement {
  $: {
    colorSchemeModeRow: HTMLElement,
    colorSchemeModeSelect: HTMLSelectElement,
    defaultFontSize: SettingsDropdownMenuElement,
    zoomLevel: HTMLSelectElement,
  };
}

// This must be kept in sync with the SystemTheme enum in
// ui/color/system_theme.h.
export enum SystemTheme {
  // Either classic or web theme.
  DEFAULT = 0,
  // <if expr="is_linux">
  GTK = 1,
  QT = 2,
  // </if>
}

const SettingsAppearancePageElementBase = SettingsViewMixin(
    RelaunchMixin(I18nMixin(PrefServiceObserverMixin(PolymerElement))));

export class SettingsAppearancePageElement extends
    SettingsAppearancePageElementBase {
  static get is() {
    return 'settings-appearance-page';
  }

  static get template() {
    return getTemplate();
  }

  static get properties() {
    return {
      /**
       * Dictionary defining page visibility.
       */
      pageVisibility_: {
        type: Object,
        value: () => pageVisibility?.appearance,
      },

      defaultZoom_: Number,

      defaultFontSizePref_: Object,
      homepageIsNewTabPagePref_: Object,
      homepagePref_: Object,
      pinContextualTaskButtonPref_: Object,
      pinnedActionsPref_: Object,
      pinSplitTabButtonPref_: Object,
      showForwardButtonPref_: Object,
      showHomeButtonPref_: Object,
      sidePanelAlignmentOverridesPref_: Object,
      sidePanelIsRightAlignedPref_: Object,
      themeIdPref_: Object,
      themePolicyColorPref_: Object,
      verticalTabsEnabledPref_: Object,

      // <if expr="is_linux">
      themeSystemThemePref_: Object,
      // </if>

      colorSchemeModeOptions_: {
        readOnly: true,
        type: Array,
        value() {
          return [
            {
              value: ColorSchemeMode.kLight,
              name: loadTimeData.getString('lightMode'),
            },
            {
              value: ColorSchemeMode.kDark,
              name: loadTimeData.getString('darkMode'),
            },
            {
              value: ColorSchemeMode.kSystem,
              name: loadTimeData.getString('systemMode'),
            },
          ];
        },
      },

      selectedColorSchemeMode_: Number,

      /**
       * List of options for the font size drop-down menu.
       */
      fontSizeOptions_: {
        readOnly: true,
        type: Array,
        value() {
          return [
            {value: 9, name: loadTimeData.getString('verySmall')},
            {value: 12, name: loadTimeData.getString('small')},
            {value: 16, name: loadTimeData.getString('medium')},
            {value: 20, name: loadTimeData.getString('large')},
            {value: 24, name: loadTimeData.getString('veryLarge')},
          ];
        },
      },

      /**
       * Predefined zoom factors to be used when zooming in/out. These are in
       * ascending order. Values are displayed in the page zoom drop-down menu
       * as percentages.
       */
      pageZoomLevels_: Array,

      themeSublabel_: String,

      themeUrl_: String,

      systemTheme_: {
        type: Object,
        value: SystemTheme.DEFAULT,
      },

      isForcedTheme_: {
        type: Boolean,
        computed: 'computeIsForcedTheme_(themePolicyColorPref_.controlledBy)',
      },

      // <if expr="is_linux">
      /**
       * Whether to show the "Custom Chrome Frame" setting.
       */
      showCustomChromeFrame_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean('showCustomChromeFrame');
        },
      },
      // </if>

      showHoverCardImagesOption_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean('showHoverCardImagesOption');
        },
      },

      showManagedThemeDialog_: Boolean,

      tabStripOptions_: {
        readOnly: true,
        type: Array,
        value() {
          return [
            {
              value: 'true',
              name: loadTimeData.getString('uiFeatureAlignSide'),
            },
            {
              value: 'false',
              name: loadTimeData.getString('uiFeatureAlignTop'),
            },
          ];
        },
      },

      showVerticalTabsEnabled_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean('showVerticalTabsEnabled');
        },
      },

      ntpSimplificationBookmarksBarEnabled_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean(
              'ntpSimplificationBookmarksBarEnabled');
        },
      },

      // The values in this array must match the BookmarkBarVisibilityState enum
      // defined in components/bookmarks/common/bookmark_bar_visibility_state.h.
      bookmarksBarOptions_: {
        readOnly: true,
        type: Array,
        value() {
          return [
            {value: 0, name: loadTimeData.getString('bookmarksBarAlwaysShow')},
            {
              value: 1,
              name: loadTimeData.getString('bookmarksBarOnlyShowOnNtp'),
            },
            {value: 2, name: loadTimeData.getString('bookmarksBarAlwaysHide')},
          ];
        },
      },

      showVerticalTabsExpandOnHoverEnabled_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean(
              'showVerticalTabsExpandOnHoverEnabled');
        },
      },

      showProjectsPanelEnabled_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean('showProjectsPanelEnabled');
        },
      },

      showEverythingMenuEnabled_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean('showEverythingMenuEnabled');
        },
      },

      showResetPinnedActionsButton_: {
        type: Boolean,
        value: false,
      },

      showCtrlTabMru_: {
        type: Boolean,
        value() {
          return loadTimeData.getBoolean('showCtrlTabMru');
        },
      },
      sidePanelAlignmentOptions_: {
        readOnly: true,
        type: Array,
        value() {
          return [
            {
              value: 'false',
              name: loadTimeData.getString('uiFeatureAlignLeft'),
            },
            {
              value: 'true',
              name: loadTimeData.getString('uiFeatureAlignRight'),
            },
          ];
        },
      },

      configurableSidePanels_: {
        readOnly: true,
        type: Array,
        value() {
          const json =
              loadTimeData.valueExists('configurableSidePanelAlignments') ?
              loadTimeData.getString('configurableSidePanelAlignments') :
              '[]';
          return JSON.parse(json);
        },
      },
    };
  }

  static get observers() {
    return [
      'defaultFontSizeChanged_(defaultFontSizePref_.value)',
      'themeChanged_(themeIdPref_.value, systemTheme_, isForcedTheme_)',
      // <if expr="is_linux">
      'systemThemePrefChanged_(themeSystemThemePref_.value)',
      // </if>
      // Keep this list in sync with `PinnedToolbarActionsModel::IsDefault()`.
      'toolbarPinningStateChanged_(' +
          'pinnedActionsPref_.value, ' +
          'showHomeButtonPref_.value, ' +
          'showForwardButtonPref_.value, ' +
          'pinSplitTabButtonPref_.value, ' +
          'pinContextualTaskButtonPref_.value)',
    ];
  }

  declare private pageVisibility_?: AppearancePageVisibility;
  declare private defaultZoom_: number;
  declare private fontSizeOptions_: DropdownMenuOptionList;
  declare private colorSchemeModeOptions_:
      Array<{value: ColorSchemeMode, name: string}>;
  declare private selectedColorSchemeMode_: ColorSchemeMode|undefined;
  declare private pageZoomLevels_: number[];
  declare private themeSublabel_: string;
  declare private themeUrl_: string;
  declare private systemTheme_: SystemTheme;
  declare private isForcedTheme_: boolean;
  declare private showHoverCardImagesOption_: boolean;
  declare private showResetPinnedActionsButton_: boolean;
  declare private showCtrlTabMru_: boolean;

  declare private defaultFontSizePref_:
      chrome.settingsPrivate.PrefObject<number>|undefined;
  declare private homepageIsNewTabPagePref_:
      chrome.settingsPrivate.PrefObject<boolean>|undefined;
  declare private homepagePref_: chrome.settingsPrivate.PrefObject<string>|
      undefined;
  declare private pinContextualTaskButtonPref_:
      chrome.settingsPrivate.PrefObject<boolean>|undefined;
  declare private pinnedActionsPref_:
      chrome.settingsPrivate.PrefObject<string[]>|undefined;
  declare private pinSplitTabButtonPref_:
      chrome.settingsPrivate.PrefObject<boolean>|undefined;
  declare private showForwardButtonPref_:
      chrome.settingsPrivate.PrefObject<boolean>|undefined;
  declare private showHomeButtonPref_:
      chrome.settingsPrivate.PrefObject<boolean>|undefined;
  declare private sidePanelAlignmentOverridesPref_:
      chrome.settingsPrivate.PrefObject<Record<string, boolean>>|undefined;
  declare private sidePanelIsRightAlignedPref_:
      chrome.settingsPrivate.PrefObject<boolean>|undefined;
  declare private themeIdPref_: chrome.settingsPrivate.PrefObject<string>|
      undefined;
  declare private themePolicyColorPref_:
      chrome.settingsPrivate.PrefObject<number>|undefined;
  declare private verticalTabsEnabledPref_:
      chrome.settingsPrivate.PrefObject<boolean>|undefined;

  // <if expr="is_linux">
  declare private themeSystemThemePref_:
      chrome.settingsPrivate.PrefObject<number>|undefined;
  declare private showCustomChromeFrame_: boolean;
  // </if>

  declare private showVerticalTabsEnabled_: boolean;
  declare private ntpSimplificationBookmarksBarEnabled_: boolean;
  declare private bookmarksBarOptions_: DropdownMenuOptionList;
  declare private showVerticalTabsExpandOnHoverEnabled_: boolean;
  declare private showProjectsPanelEnabled_: boolean;
  declare private showEverythingMenuEnabled_: boolean;
  declare private showManagedThemeDialog_: boolean;
  declare private sidePanelAlignmentOptions_: DropdownMenuOptionList;
  declare private configurableSidePanels_: Array<{id: string, label: string}>;
  declare private tabStripOptions_: DropdownMenuOptionList;
  private appearanceBrowserProxy_: AppearanceBrowserProxy =
      AppearanceBrowserProxyImpl.getInstance();
  private colorSchemeModeBrowserProxy_: CustomizeColorSchemeModeBrowserProxy =
      browserProxyFactory.getInstance();
  private setColorSchemeModeListenerId_: number|null = null;
  private metricsBrowserProxy_: MetricsBrowserProxy =
      MetricsBrowserProxyImpl.getInstance();

  override ready() {
    super.ready();

    this.$.defaultFontSize.menuOptions = this.fontSizeOptions_;
    // TODO(dschuyler): Look into adding a listener for the
    // default zoom percent.
    this.appearanceBrowserProxy_.getDefaultZoom().then(zoom => {
      this.defaultZoom_ = zoom;
    });

    this.pageZoomLevels_ =
        JSON.parse(loadTimeData.getString('presetZoomFactors'));

    this.setColorSchemeModeListenerId_ =
        this.colorSchemeModeBrowserProxy_.callbackRouter.setColorSchemeMode
            .addListener((colorSchemeMode: ColorSchemeMode) => {
              this.selectedColorSchemeMode_ =
                  this.colorSchemeModeOptions_
                      .find(mode => colorSchemeMode === mode.value)
                      ?.value;
            });
    this.colorSchemeModeBrowserProxy_.handler.initializeColorSchemeMode();
  }

  override connectedCallback() {
    super.connectedCallback();

    this.mirrorPrefs({
      'autogenerated.theme.policy.color': 'themePolicyColorPref_',
      'browser.pin_contextual_task_button': 'pinContextualTaskButtonPref_',
      'browser.pin_split_tab_button': 'pinSplitTabButtonPref_',
      'browser.show_forward_button': 'showForwardButtonPref_',
      'browser.show_home_button': 'showHomeButtonPref_',
      'extensions.theme.id': 'themeIdPref_',
      // <if expr="is_linux">
      'extensions.theme.system_theme': 'themeSystemThemePref_',
      // </if>
      'homepage': 'homepagePref_',
      'homepage_is_newtabpage': 'homepageIsNewTabPagePref_',
      'side_panel.alignment_overrides': 'sidePanelAlignmentOverridesPref_',
      'side_panel.is_right_aligned': 'sidePanelIsRightAlignedPref_',
      'toolbar.pinned_actions': 'pinnedActionsPref_',
      'vertical_tabs.enabled': 'verticalTabsEnabledPref_',
      'webkit.webprefs.default_font_size': 'defaultFontSizePref_',
    });
  }

  override disconnectedCallback() {
    super.disconnectedCallback();
    assert(this.setColorSchemeModeListenerId_);
    this.colorSchemeModeBrowserProxy_.callbackRouter.removeListener(
        this.setColorSchemeModeListenerId_);
  }

  /** @return A zoom easier read by users. */
  private formatZoom_(zoom: number): number {
    return Math.round(zoom * 100);
  }

  /**
   * @param showHomepage Whether to show home page.
   * @param isNtp Whether to use the NTP as the home page.
   * @param homepageValue If not using NTP, use this URL.
   */
  private getShowHomeSubLabel_(
      showHomepage: boolean, isNtp: boolean, homepageValue: string): string {
    if (!showHomepage) {
      return this.i18n('homeButtonDisabled');
    }
    if (isNtp) {
      return this.i18n('homePageNtp');
    }
    return homepageValue || this.i18n('customWebAddress');
  }

  private onCustomizeFontsClick_() {
    Router.getInstance().navigateTo(routes.FONTS);
  }

  private onDisableExtensionClick_() {
    this.dispatchEvent(new CustomEvent(
        'refresh-pref', {bubbles: true, composed: true, detail: 'homepage'}));
  }

  /**
   * @param value The changed font size slider value.
   */
  private defaultFontSizeChanged_() {
    // This pref is handled separately in some extensions, but here it is tied
    // to default_font_size (to simplify the UI).
    PrefService.getInstance().setPrefValue(
        'webkit.webprefs.default_fixed_font_size',
        this.defaultFontSizePref_!.value - SIZE_DIFFERENCE_FIXED_STANDARD);
  }

  private onThemeClick_() {
    this.appearanceBrowserProxy_.openCustomizeChrome();
  }

  private onCustomizeToolbarClick_() {
    this.appearanceBrowserProxy_.openCustomizeChromeToolbarSection();
  }

  private onUseDefaultClick_() {
    if (this.isForcedTheme_) {
      this.showManagedThemeDialog_ = true;
      return;
    }
    this.appearanceBrowserProxy_.useDefaultTheme();
  }

  private onResetPinnedToolbarActionsClick_() {
    this.appearanceBrowserProxy_.resetPinnedToolbarActions();
  }

  // <if expr="is_linux">
  private systemThemePrefChanged_() {
    this.systemTheme_ = this.themeSystemThemePref_!.value;
  }

  /** @return Whether to show the "USE CLASSIC" button. */
  private showUseClassic_(themeId: string): boolean {
    return !!themeId || this.systemTheme_ !== SystemTheme.DEFAULT;
  }

  /** @return Whether to show the "USE GTK" button. */
  private showUseGtk_(themeId: string): boolean {
    return (!!themeId || this.systemTheme_ !== SystemTheme.GTK) &&
        !this.appearanceBrowserProxy_.isChildAccount();
  }

  /** @return Whether to show the "USE QT" button. */
  private showUseQt_(themeId: string): boolean {
    return (!!themeId || this.systemTheme_ !== SystemTheme.QT) &&
        !this.appearanceBrowserProxy_.isChildAccount();
  }

  /**
   * @return Whether to show the secondary area where "USE CLASSIC",
   *     "USE GTK", and "USE QT" buttons live.
   */
  private showThemesSecondary_(themeId: string): boolean {
    return !!themeId || !this.appearanceBrowserProxy_.isChildAccount();
  }

  private onUseGtkClick_() {
    if (this.isForcedTheme_) {
      this.showManagedThemeDialog_ = true;
      return;
    }
    this.appearanceBrowserProxy_.useGtkTheme();
  }

  private onUseQtClick_() {
    if (this.isForcedTheme_) {
      this.showManagedThemeDialog_ = true;
      return;
    }
    this.appearanceBrowserProxy_.useQtTheme();
  }

  /** @return Whether to show the color scheme mode toggle. */
  private showColorSchemeMode_(themeId: string): boolean {
    return !!themeId ||
        this.systemTheme_ !== SystemTheme.GTK &&
        this.systemTheme_ !== SystemTheme.QT;
  }
  // </if>

  private themeChanged_() {
    if (this.themeIdPref_ === undefined || this.systemTheme_ === undefined) {
      return;
    }

    const themeId = this.themeIdPref_.value;
    if (themeId.length > 0 && themeId !== AUTOGENERATED_THEME_ID &&
        themeId !== USER_COLOR_THEME_ID && !this.isForcedTheme_) {
      assert(this.systemTheme_ === SystemTheme.DEFAULT);

      this.appearanceBrowserProxy_.getThemeInfo(themeId).then(info => {
        this.themeSublabel_ = info.name;
      });

      this.themeUrl_ = 'https://chrome.google.com/webstore/detail/' + themeId;
      return;
    }

    this.themeUrl_ = '';

    if (themeId === AUTOGENERATED_THEME_ID || themeId === USER_COLOR_THEME_ID ||
        this.isForcedTheme_) {
      this.themeSublabel_ = this.i18n('chromeColors');
      return;
    }

    // <if expr="is_linux">
    let i18nId: string;
    switch (this.systemTheme_) {
      case SystemTheme.GTK:
        i18nId = 'gtkTheme';
        break;
      case SystemTheme.QT:
        i18nId = 'qtTheme';
        break;
      default:
        i18nId = 'classicTheme';
        break;
    }
    this.themeSublabel_ = this.i18n(i18nId);
    // </if>
    // <if expr="not is_linux">
      this.themeSublabel_ = '';
    // </if>
  }

  /** @return Whether applied theme is set by policy. */
  private computeIsForcedTheme_(): boolean {
    return !!this.themePolicyColorPref_!.controlledBy;
  }

  private async toolbarPinningStateChanged_(): Promise<void> {
    this.showResetPinnedActionsButton_ =
        !(await this.appearanceBrowserProxy_.pinnedToolbarActionsAreDefault());
  }

  private isSelectedColorSchemeMode_(colorSchemeMode: ColorSchemeMode):
      boolean {
    return colorSchemeMode === this.selectedColorSchemeMode_;
  }

  private onColorSchemeModeChange_(): void {
    this.colorSchemeModeBrowserProxy_.handler.setColorSchemeMode(
        parseInt(this.$.colorSchemeModeSelect.value, 10) as ColorSchemeMode);
  }

  private onZoomLevelChange_() {
    chrome.settingsPrivate.setDefaultZoom(parseFloat(this.$.zoomLevel.value));
  }

  /** @see blink::ZoomValuesEqual(). */
  private zoomValuesEqual_(zoom1: number, zoom2: number): boolean {
    return Math.abs(zoom1 - zoom2) <= 0.001;
  }

  private showHr_(previousIsVisible: boolean, nextIsVisible: boolean): boolean {
    return previousIsVisible && nextIsVisible;
  }

  private onTabStripPositionChanged_(event: Event) {
    const dropdown = event.target as SettingsDropdownMenuElement;
    const enabled = dropdown.getSelectedValue() === 'true';
    this.appearanceBrowserProxy_.recordVerticalTabStripModeChanged(enabled);
  }

  private showEverythingMenuToggle_(): boolean {
    return !this.showProjectsPanelEnabled_ && this.showEverythingMenuEnabled_;
  }

  private onShowTabSearchButtonChange_(event: CustomEvent<boolean>) {
    this.metricsBrowserProxy_.recordAction(
        event.detail ? 'TabStripComboButton.TabSearch.Pinned' :
                       'TabStripComboButton.TabSearch.Unpinned');
  }

  private onShowProjectsPanelButtonChange_(event: CustomEvent<boolean>) {
    this.metricsBrowserProxy_.recordAction(
        event.detail ? 'TabStripComboButton.ProjectsPanel.Pinned' :
                       'TabStripComboButton.ProjectsPanel.Unpinned');
  }

  private onShowEverythingMenuButtonChange_(event: CustomEvent<boolean>) {
    this.metricsBrowserProxy_.recordAction(
        event.detail ? 'TabStripComboButton.EverythingMenu.Pinned' :
                       'TabStripComboButton.EverythingMenu.Unpinned');
  }

  private onBookmarksBarVisibilitySettingChange_(event: Event) {
    const dropdown = event.target as SettingsDropdownMenuElement;
    const value = Number.parseInt(dropdown.getSelectedValue(), 10);
    // These values map to the BookmarkBarVisibilityState enum in
    // components/bookmarks/common/bookmark_bar_visibility_state.h.
    switch (value) {
      // Equivalent to `BookmarkBarVisibilityState::kAlwaysShow`.
      case 0:
        this.metricsBrowserProxy_.recordAction(
            'Settings_BookmarkBar_AlwaysShow');
        break;
      // Equivalent to `BookmarkBarVisibilityState::kOnlyShowOnNtp`.
      case 1:
        this.metricsBrowserProxy_.recordAction(
            'Settings_BookmarkBar_OnlyShowOnNtp');
        break;
      // Equivalent to `BookmarkBarVisibilityState::kAlwaysHide`.
      case 2:
        this.metricsBrowserProxy_.recordAction(
            'Settings_BookmarkBar_AlwaysHide');
        break;
      default:
        assertNotReached();
    }
  }

  private onHoverCardImagesToggleChange_(event: Event) {
    const enabled = (event.target as SettingsToggleButtonElement).checked;
    this.appearanceBrowserProxy_.recordHoverCardImagesEnabledChanged(enabled);
  }

  private onHoverCardMemoryUsageToggleChange_(event: Event) {
    const enabled = (event.target as SettingsToggleButtonElement).checked;
    this.appearanceBrowserProxy_.recordHoverCardMemoryUsageEnabledChanged(enabled);
  }

  private showVerticalTabsExpandOnHoverSetting_(): boolean {
    if (this.verticalTabsEnabledPref_ === undefined) {
      return false;
    }

    return this.showVerticalTabsExpandOnHoverEnabled_ &&
        this.verticalTabsEnabledPref_.value;
  }


  private onManagedDialogClosed_() {
    this.showManagedThemeDialog_ = false;
  }

  private getOverrideValue_(id: string): string {
    const overrides = this.sidePanelAlignmentOverridesPref_?.value;
    const defaultIsRight = this.sidePanelIsRightAlignedPref_?.value;
    if (defaultIsRight === undefined) {
      return '';
    }
    const isRight = (overrides && overrides[id] !== undefined) ? overrides[id] :
                                                                 defaultIsRight;
    return isRight.toString();
  }

  private onOverrideAlignmentChange_(event: Event) {
    const dropdown = event.target as SettingsDropdownMenuElement;
    const entryId = dropdown.dataset['entryId']!;
    const newValue = dropdown.getSelectedValue() === 'true';
    PrefService.getInstance().setPrefDictEntry<boolean>(
        'side_panel.alignment_overrides', entryId, newValue);
  }

  // SettingsViewMixin
  override getFocusConfig() {
    const map = new Map();
    if (routes.FONTS) {
      map.set(routes.FONTS.path, '#customize-fonts-subpage-trigger');
    }
    return map;
  }

  // SettingsViewMixin implementation.
  override getAssociatedControlFor(childViewId: string): HTMLElement {
    assert(childViewId === 'fonts');
    const control = this.shadowRoot!.querySelector<HTMLElement>(
        '#customize-fonts-subpage-trigger');
    assert(
        control,
        `Failed to find associated control for child '${childViewId}'`);
    return control;
  }
}

