/**
 * Outputs chrome/browser/resources/glic/glic_api/glic_api_generated.ts.
 *
 * Reads glic mojom definitions (as json input) and outputs annotated enums and
 * structs as typescript definitions. See
 * chrome/browser/resources/glic/glic_api_impl/generate.py for
 * instructions.
 */

import {execFileSync} from 'child_process';
import * as fs from 'fs';
import * as path from 'path';
import * as process from 'process';
import {fileURLToPath} from 'url';

import {CodeWriter} from './code_writer.js';
import {MojomModel} from './converter.js';
import type {MojomAst} from './mojom_types.js';

function generateTs(c: MojomModel): string {
  const writer = new CodeWriter();

  writer.writeLine('// Copyright 2026 The Chromium Authors');
  writer.writeLine(
      '// Use of this source code is governed by a BSD-style license that' +
      ' can be');
  writer.writeLine('// found in the LICENSE file.');
  writer.writeLine();
  writer.writeLine('// THIS IS A GENERATED FILE. DO NOT MODIFY.');
  writer.writeLine('// This file is generated by');
  writer.writeLine(
      '// chrome/browser/resources/glic/glic_api_impl/generate.py');
  writer.writeLine();

  // Find unresolved types (referenced but not generated)
  const unresolvedTypes = new Set<string>();
  const BUILTIN_TYPES = new Set([
    'ArrayBuffer',
    'Uint8Array',
    'Blob',
    'ReadableStream',
    'Promise',
    'Record',
  ]);
  for (const t of c.referencedTypes) {
    if (!c.generatedNames.has(t) && !BUILTIN_TYPES.has(t)) {
      unresolvedTypes.add(t);
    }
  }

  if (unresolvedTypes.size > 0) {
    const importsList = Array.from(unresolvedTypes).sort().join(', ');
    writer.writeLine(`import type {${importsList}} from './glic_api.js';`);
    writer.writeLine();
  }

  writer.writeEnums(c.enums);
  writer.writeInterfaces(c.interfaces);
  return writer.toString();
}

function writeFile(targetPath: string, text: string, checkOnly: boolean) {
  if (fs.existsSync(targetPath)) {
    const originalText = fs.readFileSync(targetPath, 'utf-8');
    if (originalText === text) {
      return;
    }
  }

  if (checkOnly) {
    console.error(
        `${targetPath} is out of date, run ` +
        `chrome/browser/resources/glic/glic_api_impl/generate.py`);
    process.exit(1);
  }

  fs.writeFileSync(targetPath, text, 'utf-8');
}

function applyChange(targetPath: string, text: string, checkOnly: boolean) {
  const originalText = fs.readFileSync(targetPath, 'utf-8');
  const START = '\n/// BEGIN_GENERATED - DO NOT MODIFY BELOW\n';
  const END = '\n/// END_GENERATED - DO NOT MODIFY ABOVE\n';
  const startPos = originalText.indexOf(START);
  const endPos = originalText.indexOf(END);
  if (startPos < 0) {
    throw new Error(`No BEGIN_GENERATED block in ${targetPath}`);
  }
  if (endPos < 0) {
    throw new Error(`No END_GENERATED block in ${targetPath}`);
  }
  const fullText = originalText.slice(0, startPos) + START + text +
      originalText.slice(endPos);
  if (fullText === originalText) {
    return;
  }
  if (checkOnly) {
    console.error(
        `${targetPath} is out of date, run ` +
        `chrome/browser/resources/glic/glic_api_impl/generate.py`);
    process.exit(1);
  }
  fs.writeFileSync(targetPath, fullText, 'utf-8');
}

function updateGlicApiExports(
    glicApiPath: string, generatedInterfaces: Set<string>,
    generatedEnums: Set<string>, checkOnly: boolean) {
  let newExports = 'import * as generated from \'./glic_api_generated.js\';\n';

  const sortedInterfaces = Array.from(generatedInterfaces).sort();
  for (const name of sortedInterfaces) {
    let line = `export import ${name} = generated.${name};`;
    if (line.length > 80) {
      line = line.split('=').join('=\n   ');
    }
    newExports += line + '\n';
  }

  const sortedEnums = Array.from(generatedEnums).sort();
  for (const name of sortedEnums) {
    let line = `export import ${name} = generated.${name};`;
    if (line.length > 80) {
      line = line.split('=').join('=\n   ');
    }
    newExports += line + '\n';
  }

  applyChange(glicApiPath, newExports, checkOnly);
}

function getAst(dirname: string): MojomAst {
  const parsePyPath = path.resolve(dirname, 'parse.py');
  try {
    const vpythonCmd =
        process.platform === 'win32' ? 'vpython3.bat' : 'vpython3';
    const jsonStr = execFileSync(
        vpythonCmd, [parsePyPath],
        {encoding: 'utf-8', shell: process.platform === 'win32'});
    return JSON.parse(jsonStr) as MojomAst;
  } catch (e) {
    console.error('Failed to run parse.py:', e);
    process.exit(1);
  }
}

function main() {
  const args = process.argv.slice(2);
  let checkOnly = false;
  for (const arg of args) {
    if (arg === '--check-only') {
      checkOnly = true;
    }
  }

  const scriptPath = fileURLToPath(import.meta.url);
  let scriptDir = path.dirname(scriptPath);
  if (!fs.existsSync(path.join(scriptDir, 'parse.py')) &&
      process.env['GENERATE_IMPL_DIR']) {
    scriptDir = process.env['GENERATE_IMPL_DIR'];
  }

  const ast = getAst(scriptDir);

  const generatedTsPath =
      path.resolve(scriptDir, '../../glic_api/glic_api_generated.ts');
  const glicApiPath = path.resolve(scriptDir, '../../glic_api/glic_api.ts');

  const c = new MojomModel(ast.modules);
  const generatedText = generateTs(c).trimEnd() + '\n';
  writeFile(generatedTsPath, generatedText, checkOnly);

  updateGlicApiExports(
      glicApiPath, c.generatedInterfaces, c.generatedEnums, checkOnly);
}

main();
