import argparse
import io
import os

from . import parse


def _FunctionSignatureString(function_name, param_type, return_type):
    return (f'export function {function_name}(\n' +
            f'  val: {param_type}):\n' + f'    {return_type};')


def _WriteFile(target_path, text):
    if os.path.exists(target_path):
        with open(target_path, 'r') as f:
            original_text = f.read()
        if original_text == text:
            return

    with open(target_path, 'w', newline='') as f:
        f.write(text)


def GenerateConversions(converted_enums):
    source_to_ns = {
        'glic': 'mojomGlic',
        'actor': 'mojomActor',
        'glic_enums': 'mojomGlicEnums',
    }
    out = io.StringIO()
    out.write("""// Copyright 2026 The Chromium Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

// THIS IS A GENERATED FILE. DO NOT MODIFY BELOW
// This file is generated by
// chrome/browser/resources/glic/glic_api_impl/generate_impl/gen_conversions.py
// clang-format off

import type * as mojomGlic from './glic.mojom-webui.js';
import type * as mojomActor from './actor_webui.mojom-webui.js';
import type * as mojomGlicEnums from './glic_enums.mojom-webui.js';
import type * as glicApi from './glic_api/glic_api.js';

""")

    sorted_enums = sorted(converted_enums)
    for enum_name, source in sorted_enums:
        mojom_ns = source_to_ns.get(source, 'mojomGlicEnums')
        print(_FunctionSignatureString('enumToClient',
                                       f'{mojom_ns}.{enum_name}',
                                       f'glicApi.{enum_name}'),
              file=out)
        print(_FunctionSignatureString('enumToClient',
                                       f'{mojom_ns}.{enum_name} | null',
                                       f'glicApi.{enum_name} | undefined'),
              file=out)
    print('export function enumToClient(val: unknown): unknown {', file=out)
    print('  return val ?? undefined;', file=out)
    print('}', file=out)
    print('', file=out)

    for enum_name, source in sorted_enums:
        mojom_ns = source_to_ns.get(source, 'mojomGlicEnums')
        print(_FunctionSignatureString('enumFromClient',
                                       f'glicApi.{enum_name}',
                                       f'{mojom_ns}.{enum_name}'),
              file=out)
        print(_FunctionSignatureString('enumFromClient',
                                       f'glicApi.{enum_name} | undefined',
                                       f'{mojom_ns}.{enum_name} | null'),
              file=out)
    print('export function enumFromClient(val: unknown): unknown {', file=out)
    print('  return val ?? null;', file=out)
    print('}', file=out)
    return out.getvalue()


def Main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--conversions-output',
                        required=True,
                        help='Path to write enum_conversions.ts to.')
    args = parser.parse_args()

    parser_instance = parse.MojomParser()
    annotated_enums = parser_instance.GetAnnotatedEnums()
    converted_enums = [(node.mojom_name.name, source)
                       for node, source in annotated_enums]

    conversions_text = GenerateConversions(converted_enums)
    _WriteFile(args.conversions_output, conversions_text)


if __name__ == '__main__':
    Main()
