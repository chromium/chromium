/**
 * Generates enumFromClient and enumToClient code to provide
 * type safe enum conversions between glic API and Mojom.
 */

import * as fs from 'fs';
import * as process from 'process';

import {CodeWriter} from './code_writer.js';
import {MojomModel} from './converter.js';
import type {MojomAst} from './mojom_types.js';

function writeFunctionSignature(
    w: CodeWriter, functionName: string, paramType: string,
    returnType: string) {
  w.writeLine(`export function ${functionName}(`);
  w.indent();
  w.writeLine(`val: ${paramType}`);
  w.outdent();
  w.writeLine(`): ${returnType};`);
}

function writeFile(targetPath: string, text: string) {
  if (fs.existsSync(targetPath)) {
    const originalText = fs.readFileSync(targetPath, 'utf-8');
    if (originalText === text) {
      return;
    }
  }
  fs.writeFileSync(targetPath, text, 'utf-8');
}

function generateConversions(convertedEnums: Array<[string, string]>): string {
  const sourceToNs: Record<string, string> = {
    'glic': 'mojomGlic',
    'actor': 'mojomActor',
    'glic_enums': 'mojomGlicEnums',
  };

  const w = new CodeWriter();

  w.writeLine('// Copyright 2026 The Chromium Authors');
  w.writeLine(
      '// Use of this source code is governed by a BSD-style license that' +
      ' can be');
  w.writeLine('// found in the LICENSE file.');
  w.writeLine();
  w.writeLine('// THIS IS A GENERATED FILE. DO NOT MODIFY BELOW');
  w.writeLine('// This file is generated by');
  w.writeLine(
      '// chrome/browser/resources/glic/glic_api_impl/generate_impl/' +
      'gen_enum_conversions.ts');
  w.writeLine('// clang-format off');
  w.writeLine();
  w.writeLine('import type * as mojomGlic from \'./glic.mojom-webui.js\';');
  w.writeLine(
      'import type * as mojomActor from \'./actor_webui.mojom-webui.js\';');
  w.writeLine(
      'import type * as mojomGlicEnums from \'./glic_enums.mojom-webui.js\';');
  w.writeLine('import type * as glicApi from \'./glic_api/glic_api.js\';');
  w.writeLine();

  const sortedEnums =
      [...convertedEnums].sort((a, b) => a[0].localeCompare(b[0]));

  for (const [enumName, source] of sortedEnums) {
    const mojomNs = sourceToNs[source] || 'mojomGlicEnums';
    writeFunctionSignature(
        w, 'enumToClient', `${mojomNs}.${enumName}`, `glicApi.${enumName}`);
    writeFunctionSignature(
        w, 'enumToClient', `${mojomNs}.${enumName} | null`,
        `glicApi.${enumName} | undefined`);
  }
  w.writeLine('export function enumToClient(val: unknown): unknown {');
  w.writeLine('return val ?? undefined;');
  w.writeLine('}');
  w.writeLine();

  for (const [enumName, source] of sortedEnums) {
    const mojomNs = sourceToNs[source] || 'mojomGlicEnums';
    writeFunctionSignature(
        w, 'enumFromClient', `glicApi.${enumName}`, `${mojomNs}.${enumName}`);
    writeFunctionSignature(
        w, 'enumFromClient', `glicApi.${enumName} | undefined`,
        `${mojomNs}.${enumName} | null`);
  }
  w.writeLine('export function enumFromClient(val: unknown): unknown {');
  w.writeLine('return val ?? null;');
  w.writeLine('}');

  return w.toString();
}

function main() {
  const args = process.argv.slice(2);
  if (args.length < 2) {
    console.error(
        'Usage: node gen_enum_conversions.ts <ast_json_path> <output_path>');
    process.exit(1);
  }
  const astJsonPath = args[0]!;
  const outputPath = args[1]!;

  const astJson = fs.readFileSync(astJsonPath, 'utf-8');
  const ast = JSON.parse(astJson) as MojomAst;

  const converter = new MojomModel(ast.modules);
  const convertedEnums = converter.convertedEnums;

  const conversionsText = generateConversions(convertedEnums);
  writeFile(outputPath, conversionsText);
}

main();
