    // Unset policy theme and set custom theme to get button to show.
    appearancePage.set(`${POLICY_THEME_COLOR_PREF}.controlledBy`, undefined);
    appearancePage.set(`${POLICY_THEME_COLOR_PREF}.enforcement`, undefined);
