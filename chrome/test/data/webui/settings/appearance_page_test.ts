    // causes the managed theme dialog to appear.
    appearancePage.set(
        `${POLICY_THEME_COLOR_PREF}.controlledBy`, 'PRIMARY_USER');
    appearancePage.set(
        `${POLICY_THEME_COLOR_PREF}.enforcement`,
        chrome.settingsPrivate.Enforcement.ENFORCED);
