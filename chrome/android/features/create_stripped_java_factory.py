"""Generates a stripped down version of a java factory file.

A stripped down factory file is required in a feature's public_java target
during the compilation process so that features can depend on each other
without creating circular dependencies.

Afterwards, the stripped down factory's .class file is excluded from the
resulting target. The real factory uses the feature's internal implementations,
which is why it is not included in the feature's public_java target.

This script generates a stripped down factory file from real factory file to
reduce the burden of maintenance. The stripped down factory will have dummy
implementations of all public methods of the real factory.

This script uses a lightweight regex-based parser rather than a full Java
parser. It requires that the real factory file:
  * Has exactly one top-level class.
  * Does not use wildcard imports.
  * Declares public methods with bodies (abstract / native methods are ignored).
  * Does not use C-style array declarators (e.g. "String args[]").
"""

import argparse
import dataclasses
import os
import re
import sys

sys.path.append(
  os.path.join(os.path.dirname(__file__), '..', '..', '..', 'build')
)
import action_helpers

_METHOD_TEMPLATE = (
  '{MODIFIERS} {TYPE_PARAMS}{RETURN_TYPE} {NAME} ({PARAMS}){THROWS} '
  '{{ return {RETURN_VAL}; }}'
)
_FILE_TEMPLATE = '''\
// This file was generated by create_stripped_java_factory.py.

package {PACKAGE};

{IMPORTS}

{MODIFIERS} class {CLASS_NAME} {{
{METHODS}
}}
'''

# Found from:
# https://docs.oracle.com/javase/specs/jls/se7/html/jls-8.html#jls-8.4.3
_METHOD_MODIFIERS_IN_ORDER = (
  'public',
  'protected',
  'private',
  'abstract',
  'static',
  'final',
  'synchronized',
  'native',
  'strictfp',
)

# All keywords that can appear as modifiers of a member declaration. Used to
# split modifiers from the rest of a declaration.
_ALL_MODIFIERS = frozenset(
  _METHOD_MODIFIERS_IN_ORDER
  + ('default', 'transient', 'volatile', 'sealed', 'non-sealed')
)

# Matches comments, as well as string and char literals (which may contain
# characters that look like comments, braces, or annotations).
_COMMENT_OR_LITERAL_RE = re.compile(
  r'//[^\n]*'
  r'|/\*.*?\*/'
  r'|""".*?"""'
  r'|"(?:\\.|[^"\\\n])*"'
  r"|'(?:\\.|[^'\\\n])*'",
  re.DOTALL,
)
_ANNOTATION_RE = re.compile(
  r'@\s*(?!interface\b)[A-Za-z_]\w*(?:\s*\.\s*[A-Za-z_]\w*)*'
)
_ANNOTATION_ARGS_RE = re.compile(r'\s*\(')
_PACKAGE_RE = re.compile(r'^\s*package\s+([\w.]+)\s*;', re.MULTILINE)
_IMPORT_RE = re.compile(
  r'^\s*import\s+(static\s+)?([\w.]+?)(\.\*)?\s*;', re.MULTILINE
)
_TYPE_DECL_RE = re.compile(r'\b(class|interface|enum|record)\s+(\w+)')
_METHOD_RE = re.compile(
  r'^(?P<prefix>[^()]*?)(?P<name>[A-Za-z_]\w*)\s*\((?P<params>[^()]*)\)'
  r'\s*(?:throws\s+(?P<throws>[^()]+?))?\s*$',
  re.DOTALL,
)
# Matches the first identifier of every (possibly qualified) type name.
_TYPE_NAME_RE = re.compile(r'(?<![\w.])[A-Za-z_]\w*')
_TYPE_PUNCTUATION_RE = re.compile(r'\s*([<>,.\[\]])\s*')
_SPLIT_DELIMITER_RE = re.compile(r'[<>,]')
_MEMBER_DELIMITER_RE = re.compile(r'[;{}]')
_FINAL_RE = re.compile(r'^(?:final\s+)+')
_PARAM_RE = re.compile(r'^(.*?)\s*\b([A-Za-z_]\w*)$', re.DOTALL)
# Maps an opening bracket to a regex matching it or its closing bracket.
_BRACKET_RES = {
  '(': re.compile(r'[()]'),
  '<': re.compile(r'[<>]'),
  '{': re.compile(r'[{}]'),
}


@dataclasses.dataclass
class _Method:
  modifiers: list
  type_params: str
  return_type: str
  name: str
  params: list
  throws: list


def _GetDefaultReturnVal(type_name):
  if type_name in ('byte', 'short', 'int', 'long', 'float', 'double'):
    return '0'
  elif type_name == 'char':
    return "'\\0'"
  elif type_name == 'boolean':
    return 'false'
  elif type_name == 'void':
    return ''
  else:
    return 'null'


def _StripCommentsAndLiterals(content):
  """Removes comments and replaces string / char literals with empty ones."""

  def replace(match):
    text = match.group(0)
    if text.startswith('/'):
      # Keep newlines so that line-anchored regexes still work.
      return '\n' * text.count('\n') or ' '
    if text.startswith("'"):
      return "' '"
    return '""'

  return _COMMENT_OR_LITERAL_RE.sub(replace, content)


def _FindMatchingClose(content, start):
  """Returns the index of the bracket matching the one at |start|."""
  open_char = content[start]
  depth = 0
  for match in _BRACKET_RES[open_char].finditer(content, start):
    if match.group() == open_char:
      depth += 1
    else:
      depth -= 1
      if depth == 0:
        return match.start()
  raise ValueError(f'Unbalanced "{open_char}" at offset {start}')


def _StripAnnotations(content):
  """Removes all annotations (including their arguments)."""
  parts = []
  pos = 0
  while True:
    match = _ANNOTATION_RE.search(content, pos)
    if not match:
      break
    parts.append(content[pos : match.start()])
    pos = match.end()
    # Skip annotation arguments, if any.
    args_match = _ANNOTATION_ARGS_RE.match(content, pos)
    if args_match:
      pos = _FindMatchingClose(content, args_match.end() - 1) + 1
    parts.append(' ')
  parts.append(content[pos:])
  return ''.join(parts)


def _NormalizeType(type_str):
  """Collapses whitespace in a type, e.g. "Map< K, V >" -> "Map<K,V>"."""
  type_str = ' '.join(type_str.split())
  return _TYPE_PUNCTUATION_RE.sub(r'\1', type_str)


def _SplitTopLevel(text):
  """Splits |text| on commas, ignoring those within <>."""
  parts = []
  depth = 0
  part_start = 0
  for match in _SPLIT_DELIMITER_RE.finditer(text):
    c = match.group()
    if c == '<':
      depth += 1
    elif c == '>':
      depth -= 1
    elif depth == 0:
      parts.append(text[part_start : match.start()])
      part_start = match.end()
  parts.append(text[part_start:])
  return [p.strip() for p in parts if p.strip()]


def _SplitModifiers(text):
  """Returns (modifiers, remainder) for the given declaration prefix."""
  modifiers = []
  tokens = text.split()
  while tokens and tokens[0] in _ALL_MODIFIERS:
    modifiers.append(tokens.pop(0))
  return modifiers, ' '.join(tokens)


def _ParseParam(param):
  param = _FINAL_RE.sub('', param.strip())
  match = _PARAM_RE.match(param)
  assert match and match.group(1), f'Could not parse parameter: {param}'
  return _NormalizeType(match.group(1)), match.group(2)


def _ParseMethod(header):
  """Returns a _Method if |header| is a method declaration, else None."""
  if '=' in header or _TYPE_DECL_RE.search(header):
    return None
  header = header.strip()
  match = _METHOD_RE.match(header)
  if not match:
    # Fail loudly rather than silently omitting a public method.
    assert not ('(' in header and 'public' in header.split()), (
      f'Could not parse method declaration: {header}'
    )
    return None
  modifiers, rest = _SplitModifiers(match.group('prefix'))
  type_params = ''
  if rest.startswith('<'):
    end = _FindMatchingClose(rest, 0)
    type_params = _NormalizeType(rest[: end + 1])
    rest = rest[end + 1 :].strip()
  if not rest:
    # Constructor.
    return None
  params = [_ParseParam(p) for p in _SplitTopLevel(match.group('params'))]
  throws = [
    _NormalizeType(t) for t in _SplitTopLevel(match.group('throws') or '')
  ]
  return _Method(
    modifiers=modifiers,
    type_params=type_params,
    return_type=_NormalizeType(rest),
    name=match.group('name'),
    params=params,
    throws=throws,
  )


def _ParseMembers(body):
  """Returns a list of methods (with bodies) declared directly in |body|.

  |body| is the contents of a class, excluding the outer braces.
  """
  methods = []
  header_start = 0
  pos = 0
  while True:
    match = _MEMBER_DELIMITER_RE.search(body, pos)
    if not match:
      return methods
    pos = match.end()
    if match.group() == '{':
      method = _ParseMethod(body[header_start : match.start()])
      if method:
        methods.append(method)
      pos = _FindMatchingClose(body, match.start()) + 1
    header_start = pos


def _ParseImports(content):
  """Returns dict mapping from type name to import path."""
  import_dict = {}
  for match in _IMPORT_RE.finditer(content):
    if match.group(1):
      continue
    path = match.group(2)
    assert not match.group(3), f'Wildcard imports not supported: {path}'
    name = path.split('.')[-1]
    import_dict[name] = path
  return import_dict


def _ParseClass(content):
  """Returns (modifiers, name, body) of the single top-level class."""
  # Collect text that is outside of any braces.
  top_level_parts = []
  body_start = None
  body_end = None
  pos = 0
  while True:
    brace = content.find('{', pos)
    if brace == -1:
      top_level_parts.append(content[pos:])
      break
    top_level_parts.append(content[pos:brace])
    end = _FindMatchingClose(content, brace)
    if body_start is None:
      body_start, body_end = brace + 1, end
    pos = end + 1
  top_level = ''.join(top_level_parts)
  type_decls = list(_TYPE_DECL_RE.finditer(top_level))
  assert len(type_decls) == 1, 'Can only process Java files with one class'
  decl = type_decls[0]
  assert decl.group(1) == 'class', 'Can only process Java classes'

  # Modifiers are the keywords immediately preceding "class".
  preceding = re.split(r'[;}]', top_level[: decl.start()])[-1]
  modifiers = [t for t in preceding.split() if t in _ALL_MODIFIERS]
  return modifiers, decl.group(2), content[body_start:body_end]


def _ParsePublicMethodsSignatureTypes(methods):
  """Returns set of type names used in the signatures of the given methods."""
  types = set()
  for method in methods:
    signature_types = [method.type_params, method.return_type, *method.throws]
    signature_types += [param_type for param_type, _ in method.params]
    for type_str in signature_types:
      types.update(_TYPE_NAME_RE.findall(type_str))
  return types


def _FormatMethodModifiers(method_modifiers):
  unknown_modifiers = set(method_modifiers) - set(_METHOD_MODIFIERS_IN_ORDER)
  assert len(unknown_modifiers) == 0, (
    f'Unknown method modifiers: {unknown_modifiers}'
  )
  return ' '.join(
    [m for m in _METHOD_MODIFIERS_IN_ORDER if m in method_modifiers]
  )


def _FormatMethod(method):
  params = ['{} {}'.format(t, n) for t, n in method.params]
  throws = ''
  if method.throws:
    throws = ' throws ' + ', '.join(method.throws)
  type_params = method.type_params + ' ' if method.type_params else ''
  return _METHOD_TEMPLATE.format(
    MODIFIERS=_FormatMethodModifiers(method.modifiers),
    TYPE_PARAMS=type_params,
    RETURN_TYPE=method.return_type,
    NAME=method.name,
    PARAMS=', '.join(params),
    THROWS=throws,
    RETURN_VAL=_GetDefaultReturnVal(method.return_type),
  )


def _FilterAndFormatImports(import_dict, signature_types):
  """Returns formatted imports required by the passed signature types."""
  formatted_imports = [
    'import %s;' % import_dict[t] for t in signature_types if t in import_dict
  ]
  return sorted(formatted_imports)


def GenerateStrippedFactory(content):
  """Returns the stripped factory source for the given Java source."""
  content = _StripCommentsAndLiterals(content)
  content = _StripAnnotations(content)

  package_match = _PACKAGE_RE.search(content)
  assert package_match, 'No package declaration found'
  import_dict = _ParseImports(content)
  class_modifiers, class_name, class_body = _ParseClass(content)
  public_methods = [
    m for m in _ParseMembers(class_body) if 'public' in m.modifiers
  ]
  signature_types = _ParsePublicMethodsSignatureTypes(public_methods)
  formatted_imports = _FilterAndFormatImports(import_dict, signature_types)

  file_dict = {
    'PACKAGE': package_match.group(1),
    'IMPORTS': '\n'.join(formatted_imports),
    'MODIFIERS': ' '.join(class_modifiers),
    'CLASS_NAME': class_name,
    'METHODS': '\n'.join(['    ' + _FormatMethod(m) for m in public_methods]),
  }
  return _FILE_TEMPLATE.format(**file_dict)


def main(args):
  parser = argparse.ArgumentParser()
  parser.add_argument('--input', required=True, help='Input java file path.')
  parser.add_argument('--output', required=True, help='Output java file path.')
  options = parser.parse_args(args)

  with open(options.input, 'r') as f:
    content = f.read()

  with action_helpers.atomic_output(options.output, mode='w') as f:
    f.write(GenerateStrippedFactory(content))


if __name__ == '__main__':
  main(sys.argv[1:])
